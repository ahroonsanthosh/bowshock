/**
 * The verdict of W9(a) by 0009 sections 9.4 to 9.7 and 9.12, from the
 * recorded runs (code-checks.out, nodes.jsonl, ecases.jsonl, euler.jsonl
 * with euler-walls/, checks.jsonl). Computes nothing new. Writes
 * verdict.out and, where the verdict serves, served-cells.json.
 *
 *   ONLY=./judge.test.ts npx vitest run --config docs/research/fin-wave-drag/w9/vitest.config.ts
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import { exactSectionDrag } from '../../../../src/fins/section-drag';
import {
  BEVEL,
  E_CASES,
  MACH,
  NEAR_SONIC,
  THETA,
  candidateCells,
  readJsonl,
  type CheckPoint,
  type Judgement,
  type Level,
  type NodeRecord,
} from './family';

const here = dirname(fileURLToPath(import.meta.url));
const e = (v: number | null | undefined, d = 3) => (v === null || v === undefined ? '-' : v.toExponential(d));

interface CheckRecord extends CheckPoint {
  readonly libraryExact: boolean;
  readonly judgement: Judgement;
  readonly epsLo: number;
  readonly epsHi: number;
  readonly inside: boolean | null;
}
interface ECase {
  readonly case: string;
  readonly bevel: number;
  readonly cdSE: number;
  readonly firstReflection: number;
  readonly levels: readonly Level[];
  readonly judgement: Judgement;
  readonly flat: readonly { x: number; p: number }[];
  readonly bevel256: readonly { x: number; p: number }[];
}
interface EulerLevel {
  readonly case: string;
  readonly level: number;
  readonly ni: number;
  readonly nj: number;
  readonly iterations: number;
  readonly converged: boolean;
  readonly cd: number;
  readonly overSE: number;
}

const interp = (pts: readonly { x: number; p: number }[], x: number) => {
  for (let i = 0; i + 1 < pts.length; i++) {
    const a = pts[i]!;
    const b = pts[i + 1]!;
    if (x >= a.x && x <= b.x) return b.x === a.x ? a.p : a.p + ((b.p - a.p) * (x - a.x)) / (b.x - a.x);
  }
  throw new RangeError(`x = ${x} is outside the method's wall points`);
};

test('W9(a): the verdict', () => {
  const out: string[] = ["# W9(a)'s verdict by 0009 sections 9.4 to 9.7 and 9.12 (generated by judge.test.ts; do not edit)", ''];
  let serves = true;
  const stop = (why: string) => {
    serves = false;
    out.push(`- **Nothing is served:** ${why}`);
  };

  // The gate of the code checks (9.3 with 9.12).
  const checksOut = readFileSync(join(here, 'code-checks.out'), 'utf8');
  const gate = /the gate for the family as 9\.12 rules it[^:]*: true/.test(checksOut);
  out.push('## The gate of the code checks', '', `- code-checks.out: ${gate ? 'passes' : 'does not pass'}`, '');
  if (!gate) stop('the code checks do not pass the gate');

  // The nodes.
  const nodes = readJsonl<NodeRecord>(join(here, 'nodes.jsonl'));
  const byKey = new Map(nodes.map((n) => [n.key, n]));
  const passed = nodes.filter((n) => n.judgement.pass);
  const failed = nodes.filter((n) => !n.judgement.pass);
  const exact = nodes.filter((n) => n.libraryExact);
  const exactBad = exact.filter((n) => n.exactHolds !== true);
  const nuConverged = nodes.filter((n) => n.nuConverged);
  const both = nodes.filter((n) => n.nuAgrees !== null);
  const disagree = nodes.filter((n) => n.nuAgrees === false);
  const nearSonic = nodes.filter((n) => n.m1 < NEAR_SONIC);
  out.push(
    '## The nodes (9.4, 9.5)',
    '',
    `- computed: ${nodes.length} of 1392; passing 9.5: ${passed.length}; failing: ${failed.length}`,
    `- by (a): ${passed.filter((n) => n.judgement.why === 'passes by (a)').length}; by (b): ${passed.filter((n) => n.judgement.why === 'passes by (b)').length}`,
    `- the library calls exact: ${exact.length}; |eps| <= 1e-12 at every level: ${exact.length - exactBad.length} (a violation stops the runs, 9.4)`,
    `- the nu diagnostic (9.12): converged by 9.5 at ${nuConverged.length} nodes; both converged at ${both.length}, agreeing within the larger U at ${both.length - disagree.length}; the pressure run passing where the nu run did not converge (no second check): ${passed.filter((n) => !n.nuConverged).length}`,
    `- below Mach 1.1 behind the shock (computed, serving nothing): ${nearSonic.length} nodes, passing 9.5: ${nearSonic.filter((n) => n.judgement.pass).length}`,
    `- eps over the passing nodes: ${e(Math.min(...passed.map((n) => n.judgement.value!)))} to ${e(Math.max(...passed.map((n) => n.judgement.value!)))}; U at most ${e(Math.max(...passed.map((n) => n.judgement.U!)))}`,
    '',
  );
  if (nodes.length !== 1392) stop(`only ${nodes.length} of 1392 nodes are recorded`);
  if (exactBad.length > 0) stop(`${exactBad.length} nodes the library calls exact give |eps| above 1e-12`);
  if (disagree.length > 0) stop(`${disagree.length} nodes where the nu diagnostic disagrees`);
  if (failed.length > 0) {
    out.push('| node | half-angle | bevel | Mach | M behind the shock | why it fails 9.5 | nu run |', '| --- | --- | --- | --- | --- | --- | --- |');
    for (const n of failed) {
      out.push(`| ${n.key} | ${n.theta} | ${n.bevel.toFixed(4)} | ${n.mach} | ${n.m1.toFixed(3)} | ${n.judgement.why} | ${n.nuConverged ? 'converges' : n.nu.judgement.why} |`);
    }
    out.push('');
  }

  // Candidate cells and check points (9.6).
  const cells = candidateCells(byKey);
  const checks = readJsonl<CheckRecord>(join(here, 'checks.jsonl'));
  const notConverged = checks.filter((c) => !c.judgement.pass);
  const outside = checks.filter((c) => c.inside === false);
  const removed = new Set(notConverged.map((c) => c.cell.join('|')));
  const served = cells.filter((c) => !removed.has(`${c.i}|${c.j}|${c.k}`));
  const kinds = ['population', 'random', 'centre'] as const;
  out.push(
    '## Candidate cells and check points (9.6)',
    '',
    `- candidate cells: ${cells.length}`,
    `- check points: ${checks.length} (${kinds.map((k) => `${k} ${checks.filter((c) => c.kind === k).length}`).join(', ')})`,
    `- failing 9.5 (each removes its cell): ${notConverged.length}, ${((100 * notConverged.length) / Math.max(1, checks.length)).toFixed(2)}% (the cap is 2%)`,
    `- converged outside their cell's band (any refuses all): ${outside.length}`,
    `- the band's width over the candidate cells: ${e(Math.min(...cells.map((c) => c.epsHi - c.epsLo)), 1)} to ${e(Math.max(...cells.map((c) => c.epsHi - c.epsLo)), 1)}; eps_lo ${e(Math.min(...cells.map((c) => c.epsLo)), 1)} to ${e(Math.max(...cells.map((c) => c.epsLo)), 1)}, eps_hi ${e(Math.min(...cells.map((c) => c.epsHi)), 1)} to ${e(Math.max(...cells.map((c) => c.epsHi)), 1)}`,
    `- cells served if the rest passes: ${served.length}`,
    '',
  );
  if (notConverged.length > 0) {
    out.push('| check point | half-angle | bevel | Mach | why it fails 9.5 |', '| --- | --- | --- | --- | --- |');
    for (const c of notConverged) out.push(`| ${c.id} | ${c.theta.toFixed(3)} | ${c.bevel.toFixed(4)} | ${c.mach.toFixed(3)} | ${c.judgement.why} |`);
    out.push('');
  }
  if (outside.length > 0) {
    out.push('| check point | half-angle | bevel | Mach | eps -+ U | its cell\'s band |', '| --- | --- | --- | --- | --- | --- |');
    for (const c of outside) {
      out.push(`| ${c.id} | ${c.theta.toFixed(3)} | ${c.bevel.toFixed(4)} | ${c.mach.toFixed(3)} | ${e(c.judgement.value! - c.judgement.U!)} to ${e(c.judgement.value! + c.judgement.U!)} | ${e(c.epsLo)} to ${e(c.epsHi)} |`);
    }
    out.push('');
  }
  if (checks.length === 0) stop('the check points have not been run');
  if (notConverged.length > 0.02 * checks.length) stop('more than 2% of the check points fail 9.5');
  if (outside.length > 0) stop(`${outside.length} converged check points lie outside their cell's band`);
  const closest = checks
    .filter((c) => c.inside === true)
    .map((c) => Math.min(c.judgement.value! - c.judgement.U! - c.epsLo, c.epsHi - c.judgement.value! - c.judgement.U!))
    .sort((a, b) => a - b);
  if (closest.length > 0) out.push(`- the closest a converged check point comes to its band's edge: ${e(closest[0])} in eps`, '');

  // The Euler check (9.7).
  const ecases = new Map(readJsonl<ECase>(join(here, 'ecases.jsonl')).map((c) => [c.case, c]));
  const euler = readJsonl<EulerLevel>(join(here, 'euler.jsonl'));
  out.push('## The Euler check (9.7)', '');
  let eulerPass = true;
  for (const name of ['E1', 'E2', 'E3']) {
    const ec = ecases.get(name);
    const lv = [0, 1, 2, 3].map((k) => euler.find((r) => r.case === name && r.level === k));
    out.push(`### ${name}`, '');
    if (ec === undefined || lv.some((r) => r === undefined)) {
      out.push('- not complete', '');
      eulerPass = false;
      continue;
    }
    const c = E_CASES[name]!;
    const se = exactSectionDrag(c.section, c.mach, { neglectReflectedWaves: true });
    const moc = ec.cdSE * (1 + ec.judgement.value!);
    const mocU = ec.cdSE * ec.judgement.U!;
    out.push(
      `- the method: eps ${ec.levels.map((l) => e(l.eps)).join(', ')} at N = 16 to 256; ${ec.judgement.why}; cd ${moc.toPrecision(8)} +- ${e(mocU, 1)} (eps ${e(ec.judgement.value)})`,
      `- Euler: ${lv.map((r) => `level ${r!.level} (${r!.ni} x ${r!.nj}, ${r!.iterations} iterations${r!.converged ? '' : ', AT THE CAP'}) ${(100 * r!.overSE).toFixed(4)}%`).join('; ')} over shock-expansion`,
    );
    const conv = ec.judgement.pass && lv.every((r) => r!.converged);
    if (!conv) out.push('- the method or an Euler solve did not converge: the check fails');
    const [D1, D2, D3] = [lv[1]!.cd, lv[2]!.cd, lv[3]!.cd];
    let lo: number;
    let hi: number;
    let shrink = true;
    if ((D2 - D1) * (D3 - D2) > 0) {
      shrink = Math.abs(D3 - D2) < Math.abs(D2 - D1);
      const x = D3 + (D3 - D2) / (Math.SQRT2 - 1);
      lo = Math.min(D3, x);
      hi = Math.max(D3, x);
    } else {
      lo = D3 - 2.5 * Math.abs(D3 - D2);
      hi = D3 + 2.5 * Math.abs(D3 - D2);
    }
    lo -= mocU;
    hi += mocU;
    const ea = shrink && moc >= lo && moc <= hi;
    out.push(
      `- (E-a): ${(D2 - D1) * (D3 - D2) > 0 ? 'monotone' : 'not monotone'}; differences ${(100 * (D2 - D1)) / se.cd >= 0 ? '+' : ''}${((100 * (D2 - D1)) / se.cd).toFixed(4)}% then ${((100 * (D3 - D2)) / se.cd).toFixed(4)}% (${shrink ? 'shrinking' : 'NOT shrinking'}); interval ${((100 * lo) / se.cd - 100).toFixed(4)}% to ${((100 * hi) / se.cd - 100).toFixed(4)}% over shock-expansion; the method ${((100 * moc) / se.cd - 100).toFixed(4)}%: ${ea ? 'passes' : 'FAILS'}`,
    );
    // (E-b), on each window.
    const b = c.bevel;
    const p2 = se.upper.faces[1]!.pressureRatio;
    const p3 = se.upper.faces[2]!.pressureRatio;
    const windows = [
      { name: 'flat', from: ec.firstReflection, to: 1 - b - 0.2 * b, se: p2, moc: ec.flat },
      { name: 'bevel', from: 1 - b + 0.2 * b, to: 1 - 0.2 * b, se: p3, moc: ec.bevel256 },
    ];
    let eb = true;
    out.push('', '| window | level | faces | e_k | s_k |', '| --- | --- | --- | --- | --- |');
    for (const w of windows) {
      const ek: number[] = [];
      const sk: number[] = [];
      for (const k of [0, 1, 2, 3]) {
        const faces = JSON.parse(readFileSync(join(here, 'euler-walls', `${name}-L${k}.json`), 'utf8')) as {
          x: number;
          y: number;
          p: number;
          length: number;
        }[];
        const inW = faces.filter((f) => f.y > 0 && f.x >= w.from && f.x <= w.to);
        let len = 0;
        let se2 = 0;
        let ss2 = 0;
        for (const f of inW) {
          const pm = interp(w.moc, f.x);
          len += f.length;
          se2 += f.length * (f.p - pm) ** 2;
          ss2 += f.length * (f.p - w.se) ** 2;
        }
        ek.push(Math.sqrt(se2 / len));
        sk.push(Math.sqrt(ss2 / len));
        out.push(`| ${w.name} | ${k} | ${inW.length} | ${e(ek[k])} | ${e(sk[k])} |`);
      }
      const ok = ek[3]! < ek[2]! && ek[3]! <= sk[3]! / 2;
      eb &&= ok;
      out.push(`| ${w.name}: e_3 < e_2 and e_3 <= s_3 / 2 | | | ${ok ? 'passes' : 'FAILS'} | |`);
    }
    out.push('', `- (E-b): ${eb ? 'passes' : 'FAILS'}`, '');
    eulerPass &&= conv && ea && eb;
  }
  out.push(`- the Euler check: ${eulerPass ? 'passes in all three cases' : 'FAILS'}`, '');
  if (!eulerPass) stop('the Euler check (9.7) does not pass');

  out.push('## Verdict', '', serves ? `- **Served:** ${served.length} cells, by 0009 section 9.6.` : '- nothing is served (above).', '');
  writeFileSync(join(here, 'verdict.out'), out.join('\n'));
  if (serves) {
    writeFileSync(
      join(here, 'served-cells.json'),
      JSON.stringify({
        theta: THETA,
        bevel: BEVEL,
        mach: MACH,
        cells: served.map((c) => ({ i: c.i, j: c.j, k: c.k, epsLo: Number(c.epsLo.toFixed(3)), epsHi: Number(c.epsHi.toFixed(3)) })),
      }),
    );
  }
});
