/**
 * W9(a)'s nodes (0009 section 9.4 and 9.11, step 2): every node of the grid
 * with an attached shock and supersonic flow behind it, at the five levels,
 * with the registered interpolation (the pressure, 9.12) and the nu
 * diagnostic beside it; judged by 9.5. One line per node in nodes.jsonl as
 * it finishes, each solve logged in tests/tmp-w9/solves-nodes.jsonl so that
 * a restart loses at most the solve in progress; a restart skips the nodes
 * recorded. The runs stop (the test fails after writing the node's line)
 * where a node the library calls exact gives |eps| above 1e-12 at any level
 * (9.4), or where both runs converge and disagree beyond the larger U
 * (9.12). Also writes diagnostic-r.out (9.12: R_N at 10 deg and Mach 1.5).
 *
 *   ONLY=./nodes.test.ts npx vitest run --config docs/research/fin-wave-drag/w9/vitest.config.ts
 */

import { execSync } from 'node:child_process';
import { appendFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import { analyticReflection, methodReflection } from '../../../../tests/support/planar-characteristics-checks';
import {
  BEVEL,
  LEVELS,
  MACH,
  THETA,
  SolveLog,
  behindShock,
  judge95,
  levelsOf,
  nodeKey,
  readJsonl,
  shockExpansion,
  type NodeRecord,
} from './family';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../../..');
const NODES = join(here, 'nodes.jsonl');

test('W9(a): the nodes', () => {
  const commit = execSync('git rev-parse --short HEAD', { cwd: here }).toString().trim();
  const dirty = execSync('git status --porcelain -- src', { cwd: root }).toString().trim();
  if (dirty !== '') throw new Error('src has uncommitted changes: the runs record the commit they ran on');

  // 9.12's diagnostic, with no gate: R_N at the served corner with the lowest Mach number behind the shock.
  if (!existsSync(join(here, 'diagnostic-r.out'))) {
    const R = analyticReflection(10, 1.5);
    const rows = LEVELS.map((N) => {
      const rn = methodReflection(10, 1.5, N);
      return `| ${N} | ${rn.toFixed(6)} | ${Math.abs(rn - R).toExponential(3)} |`;
    });
    writeFileSync(
      join(here, 'diagnostic-r.out'),
      [
        '# R_N at 10 deg and Mach 1.5 (0009 section 9.12, a diagnostic with no gate; generated by nodes.test.ts)',
        '',
        `- commit ${commit}; Mach ${behindShock(10, 1.5)!.toFixed(4)} behind the shock; R = ${R.toFixed(6)}`,
        '',
        '| N | R_N | |R_N - R| |',
        '| --- | --- | --- |',
        ...rows,
        '',
      ].join('\n'),
    );
  }

  mkdirSync(join(root, 'tests/tmp-w9'), { recursive: true });
  const log = new SolveLog(join(root, 'tests/tmp-w9/solves-nodes.jsonl'));
  const done = new Set(readJsonl<NodeRecord>(NODES).map((n) => n.key));
  let count = done.size;
  const t0 = Date.now();
  for (let i = 0; i < THETA.length; i++) {
    for (let k = 0; k < MACH.length; k++) {
      const theta = THETA[i]!;
      const mach = MACH[k]!;
      const m1 = behindShock(theta, mach);
      if (m1 === undefined) continue;
      for (let j = 0; j < BEVEL.length; j++) {
        const key = nodeKey(i, j, k);
        if (done.has(key)) continue;
        const bevel = BEVEL[j]!;
        const se = shockExpansion(theta, bevel, mach);
        const levels = levelsOf(key, theta, bevel, mach, 'pressure', se.cd, log);
        const nuLevels = levelsOf(key, theta, bevel, mach, 'nu', se.cd, log);
        const judgement = judge95(levels);
        const nuJudgement = judge95(nuLevels);
        const nuConverged = nuJudgement.pass;
        const nuAgrees =
          judgement.pass && nuConverged
            ? Math.abs(judgement.value! - nuJudgement.value!) <= Math.max(judgement.U!, nuJudgement.U!)
            : null;
        const exactHolds = se.exact ? levels.every((l) => l.eps !== null && Math.abs(l.eps) <= 1e-12) : null;
        const record: NodeRecord = {
          key,
          theta,
          bevel,
          mach,
          m1,
          libraryExact: se.exact,
          cdSE: se.cd,
          levels,
          judgement,
          nu: { levels: nuLevels, judgement: nuJudgement },
          nuConverged,
          nuAgrees,
          exactHolds,
          commit,
        };
        appendFileSync(NODES, JSON.stringify(record) + '\n');
        count++;
        if (count % 50 === 0) {
          console.log(`${count} nodes, ${((Date.now() - t0) / 1000).toFixed(0)} s`);
        }
        if (exactHolds === false) {
          throw new Error(
            `the runs stop (9.4): node ${key} (${theta} deg, b ${bevel}, Mach ${mach}), which the library calls exact, ` +
              `gives eps ${levels.map((l) => l.eps).join(', ')}`,
          );
        }
        if (nuAgrees === false) {
          throw new Error(
            `the runs stop (9.12): node ${key} (${theta} deg, b ${bevel}, Mach ${mach}): pressure ${judgement.value} +- ${judgement.U}, ` +
              `nu ${nuJudgement.value} +- ${nuJudgement.U}`,
          );
        }
      }
    }
  }
  console.log(`done: ${count} nodes`);
});
