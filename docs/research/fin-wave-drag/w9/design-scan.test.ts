/**
 * The method's own values that chose 0009 section 9.13's cases, computed
 * before that section was written and before any of its Euler solves: at
 * candidate hexagons, the first landing of the reflected waves, the part of
 * eps on the bevel window and the mean pressure change on the bevel and the
 * flat windows, at N = 128 and 256 with the registered interpolation.
 * Writes design-scan.out. No Euler solve.
 *
 *   ONLY=./design-scan.test.ts npx vitest run --config docs/research/fin-wave-drag/w9/vitest.config.ts
 */

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import { hexagonal } from '../../../../src/fins/section';
import { exactSectionDrag } from '../../../../src/fins/section-drag';
import { hexagonCharacteristics } from '../../../../src/validation/planar-characteristics';
import { BEVEL, DEG } from './family';

const here = dirname(fileURLToPath(import.meta.url));

type Pt = { readonly x: number; readonly p: number };
/** Trapezoid integral of (p - c) over [a, b] on a wall list, linear between its points. */
function windowIntegral(pts: readonly Pt[], a: number, b: number, c: number): number {
  const at = (x: number) => {
    for (let i = 0; i + 1 < pts.length; i++) {
      const u = pts[i]!;
      const v = pts[i + 1]!;
      if (x >= u.x && x <= v.x) return v.x === u.x ? u.p : u.p + ((v.p - u.p) * (x - u.x)) / (v.x - u.x);
    }
    throw new RangeError(`x = ${x} is outside the wall list`);
  };
  const xs = [a, ...pts.map((q) => q.x).filter((x) => x > a && x < b), b];
  let s = 0;
  for (let i = 0; i + 1 < xs.length; i++) s += 0.5 * (at(xs[i]!) - c + at(xs[i + 1]!) - c) * (xs[i + 1]! - xs[i]!);
  return s;
}

test("W9(a): the method's values that chose 9.13's cases", () => {
  const commit = execSync('git rev-parse --short HEAD', { cwd: here }).toString().trim();
  const cases: [number, number, number][] = [];
  for (const j of [4, 5, 6, 7]) for (const m of [1.7, 1.8, 1.9, 2.0, 2.2, 2.4, 2.8, 3.0]) cases.push([15, BEVEL[j]!, m]);
  for (const t of [12, 13, 14]) for (const m of [1.8, 2.0]) cases.push([t, BEVEL[6]!, m]);
  cases.push([15, 0.12, 1.8], [10, BEVEL[6]!, 1.5], [10, BEVEL[7]!, 1.5], [10, BEVEL[8]!, 1.5]);
  const out = [
    "# The method's values that chose 0009 section 9.13's cases (generated by design-scan.test.ts; no Euler solve)",
    '',
    `- commit ${commit}; the method at N = 128 and 256, the pressure interpolated (9.12)`,
    '- eps: the method over shock-expansion with the reflections neglected, minus one (N = 256)',
    "- bevel window [1 - 0.75 b, 1 - 0.25 b]: eps_W, its part of eps, (2 / (q cd_SE)) times the integral of (p - p3)(-tan theta) dx; and the mean of (p - p3) over it, over the free stream's pressure",
    '- flat window [first landing, 1 - 1.25 b]: the mean of (p - p2) over it, over the free stream\'s pressure',
    '- level-0 cells on a bevel: round(b / 0.025), section 2.4\'s grid',
    '',
    '| half-angle | b | Mach | eps | eps_W | eps_W(256) - eps_W(128) | bevel mean dp | first landing | flat mean dp | level-0 bevel cells |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const [theta, b, mach] of cases) {
    const se = exactSectionDrag(hexagonal(2 * b * Math.tan(theta * DEG), b), mach, { neglectReflectedWaves: true });
    const q = 0.7 * mach * mach;
    const p2 = se.upper.faces[1]!.pressureRatio;
    const p3 = se.upper.faces[2]!.pressureRatio;
    const tan = Math.tan(theta * DEG);
    const w0 = 1 - 0.75 * b;
    const w1 = 1 - 0.25 * b;
    const at = [128, 256].map((N) => {
      const s = hexagonCharacteristics(mach, theta * DEG, b, N);
      const bevelInt = windowIntegral(s.bevel, w0, w1, p3);
      const f1 = 1 - 1.25 * b;
      return {
        eps: s.cd / se.cd - 1,
        epsW: (2 * -tan * bevelInt) / (q * se.cd),
        bevelMean: bevelInt / (w1 - w0),
        landing: s.firstLanding,
        flatMean: f1 > s.firstLanding ? windowIntegral(s.flat, s.firstLanding, f1, p2) / (f1 - s.firstLanding) : NaN,
      };
    });
    const v = at[1]!;
    out.push(
      `| ${theta} | ${b.toFixed(4)} | ${mach} | ${(100 * v.eps).toFixed(4)}% | ${(100 * v.epsW).toFixed(4)}% | ${(v.epsW - at[0]!.epsW).toExponential(1)} | ${v.bevelMean.toExponential(2)} | ${v.landing.toFixed(4)} | ${v.flatMean.toExponential(2)} | ${Math.round(b / 0.025)} |`,
    );
  }
  writeFileSync(join(here, 'design-scan.out'), out.join('\n') + '\n');
});
