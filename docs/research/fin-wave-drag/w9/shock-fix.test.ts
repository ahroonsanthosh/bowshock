/**
 * The check of 0009 section 9.14's change and the re-judgement it
 * registers, on the change's commit:
 *
 * - (3) code-checks.out reproduced: compares the committed code-checks.out
 *   with a re-run's output saved at tests/tmp-w9/code-checks-rerun.out,
 *   every line but the one naming the commit;
 * - (4) every node and check point whose registered run completed all five
 *   levels, re-run with the pressure interpolation, must give the same eps
 *   and mass balance at every level, to the bit (shock-fix-identity.jsonl,
 *   one line per case, resumable);
 * - the 4 nodes re-run with both interpolations as nodes.test.ts ran them
 *   (shock-fix-nodes.jsonl), the 7 check points re-run, the candidate cells
 *   recomputed, and every new candidate cell given its centre and the
 *   population's refused hexagons in it (shock-fix-checks.jsonl); the 200
 *   random points stay as drawn.
 *
 * Writes shock-fix.out. The records of 2026-10-30 (nodes.jsonl,
 * checks.jsonl, verdict.out) are not changed.
 *
 *   ONLY=./shock-fix.test.ts npx vitest run --config docs/research/fin-wave-drag/w9/vitest.config.ts
 */

import { execSync } from 'node:child_process';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import type { SymmetricSection } from '../../../../src/fins/section';
import { librarySection, totalReasons } from '../../refusals/evaluate';
import { MACH_BANDS, drawAltitude, mulberry32 as populationRandom, population } from '../../refusals/population';
import {
  BEVEL,
  DEG,
  LEVELS,
  MACH,
  THETA,
  candidateCells,
  cellIndex,
  judge95,
  readJsonl,
  shockExpansion,
  solve,
  type Cell,
  type CheckPoint,
  type Judgement,
  type Level,
  type NodeRecord,
} from './family';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../../..');

interface CheckRecord extends CheckPoint {
  readonly cdSE: number;
  readonly levels: readonly Level[];
  readonly judgement: Judgement;
  readonly epsLo: number;
  readonly epsHi: number;
  readonly inside: boolean | null;
}

const shockFailed = (levels: readonly Level[]) => levels.some((l) => l.failure?.includes('shock point'));

/** As checks.test.ts: the population's refused hexagons at Mach 1.5 and above in the given cells. */
function populationCheckPoints(cellKeys: ReadonlySet<string>): CheckPoint[] {
  const out: CheckPoint[] = [];
  const rand = populationRandom(7);
  for (const rocket of population(2000)) {
    MACH_BANDS.forEach(([lo, hi]) => {
      const mach = lo + (hi - lo) * (0.0005 + 0.999 * rand());
      const altitudeKm = drawAltitude(rand(), rand());
      if (rocket.section !== 'bevel-both' || !(mach >= 1.5)) return;
      if (!totalReasons(rocket, { mach, altitudeKm }).includes('sectionReflected')) return;
      const section = librarySection(rocket) as SymmetricSection;
      const bevel = section.x[1]!;
      const theta = Math.atan(section.halfThickness[1]! / bevel) / DEG;
      const cell = [cellIndex(THETA, theta), cellIndex(BEVEL, bevel), cellIndex(MACH, mach)] as const;
      if (!cellKeys.has(cell.join('|'))) return;
      out.push({ id: `population-${rocket.id}-${mach.toFixed(6)}`, kind: 'population', theta, bevel, mach, cell });
    });
  }
  return out;
}

function checkRecord(p: CheckPoint, cell: Cell, commit: string): CheckRecord & { commit: string } {
  const se = shockExpansion(p.theta, p.bevel, p.mach);
  const levels = LEVELS.map((N) => solve(p.theta, p.bevel, p.mach, N, 'pressure', se.cd));
  const judgement = judge95(levels);
  const inside = judgement.pass
    ? judgement.value! - judgement.U! >= cell.epsLo && judgement.value! + judgement.U! <= cell.epsHi
    : null;
  return { ...p, cdSE: se.cd, levels, judgement, epsLo: cell.epsLo, epsHi: cell.epsHi, inside, commit };
}

test("W9(a): the check of 9.14's change and the re-judgement", () => {
  const commit = execSync('git rev-parse --short HEAD', { cwd: here }).toString().trim();
  const dirty = execSync('git status --porcelain -- src', { cwd: root }).toString().trim();
  if (dirty !== '') throw new Error('src has uncommitted changes: the runs record the commit they ran on');
  const out: string[] = [
    "# The check of 0009 section 9.14's change and the re-judgement (generated by shock-fix.test.ts; do not edit)",
    '',
    `- commit ${commit}`,
    '',
  ];

  // (3) code-checks.out reproduced.
  const rerunPath = join(root, 'tests/tmp-w9/code-checks-rerun.out');
  if (!existsSync(rerunPath)) throw new Error('run code-checks.test.ts first and save its output as tests/tmp-w9/code-checks-rerun.out');
  const strip = (s: string) => s.split('\n').filter((l) => !l.startsWith('- commit '));
  const was = strip(readFileSync(join(here, 'code-checks.out'), 'utf8'));
  const now = strip(readFileSync(rerunPath, 'utf8'));
  const differing = was.flatMap((l, i) => (l === now[i] ? [] : [i]));
  const sameLength = was.length === now.length;
  const checksSame = sameLength && differing.length === 0;
  out.push(
    '## (3) The code checks re-run',
    '',
    `- code-checks.out (commit e09cf7e) against the re-run on ${commit}, every line but the one naming the commit: ${checksSame ? `identical (${was.length} lines)` : `DIFFERENT (${sameLength ? `${differing.length} lines differ` : `${was.length} against ${now.length} lines`})`}`,
    '',
  );

  // (4) The same values to the bit.
  const nodes = readJsonl<NodeRecord>(join(here, 'nodes.jsonl'));
  const checks = readJsonl<CheckRecord>(join(here, 'checks.jsonl'));
  const IDENT = join(here, 'shock-fix-identity.jsonl');
  const identDone = new Map(readJsonl<{ id: string; identical: boolean }>(IDENT).map((r) => [r.id, r.identical]));
  const cases = [
    ...nodes.filter((n) => !shockFailed(n.levels)).map((n) => ({ id: `node-${n.key}`, r: n })),
    ...checks.filter((c) => !shockFailed(c.levels)).map((c) => ({ id: c.id, r: c })),
  ];
  let k = identDone.size;
  const t0 = Date.now();
  for (const { id, r } of cases) {
    if (identDone.has(id)) continue;
    const levels = LEVELS.map((N) => solve(r.theta, r.bevel, r.mach, N, 'pressure', r.cdSE));
    const diff = levels.flatMap((l, i) => {
      const old = r.levels[i]!;
      return l.eps === old.eps && l.mass === old.mass && l.failure === old.failure ? [] : [{ N: l.N, was: [old.eps, old.mass], now: [l.eps, l.mass] }];
    });
    appendFileSync(IDENT, JSON.stringify({ id, identical: diff.length === 0, diff, commit }) + '\n');
    identDone.set(id, diff.length === 0);
    k++;
    if (k % 200 === 0) console.log(`${k} of ${cases.length} re-run, ${((Date.now() - t0) / 1000).toFixed(0)} s`);
  }
  const moved = [...identDone].filter(([, same]) => !same);
  const nodeCount = cases.filter((c) => c.id.startsWith('node-')).length;
  out.push(
    '## (4) Every completed node and check point re-run, the pressure interpolation',
    '',
    `- re-run: ${identDone.size} (${nodeCount} nodes, ${identDone.size - nodeCount} check points); the same eps and mass balance at all five levels, to the bit: ${identDone.size - moved.length}; different: ${moved.length}${moved.length > 0 ? ` (${moved.map(([id]) => id).join(', ')})` : ''}`,
    '',
  );
  if (!checksSame || moved.length > 0) {
    out.push('- **The check of the change fails: the work stops for a report, and the change is not used.**', '');
    writeFileSync(join(here, 'shock-fix.out'), out.join('\n'));
    throw new Error('the check of 9.14 fails');
  }

  // The re-judgement: the 4 nodes, with both interpolations.
  const NODES_FIX = join(here, 'shock-fix-nodes.jsonl');
  const fixedNodes = new Map(readJsonl<NodeRecord>(NODES_FIX).map((n) => [n.key, n]));
  for (const n of nodes.filter((x) => shockFailed(x.levels))) {
    if (fixedNodes.has(n.key)) continue;
    const se = shockExpansion(n.theta, n.bevel, n.mach);
    const levels = LEVELS.map((N) => solve(n.theta, n.bevel, n.mach, N, 'pressure', se.cd));
    const nuLevels = LEVELS.map((N) => solve(n.theta, n.bevel, n.mach, N, 'nu', se.cd));
    const judgement = judge95(levels);
    const nuJudgement = judge95(nuLevels);
    const nuConverged = nuJudgement.pass;
    const nuAgrees =
      judgement.pass && nuConverged
        ? Math.abs(judgement.value! - nuJudgement.value!) <= Math.max(judgement.U!, nuJudgement.U!)
        : null;
    const exactHolds = se.exact ? levels.every((l) => l.eps !== null && Math.abs(l.eps) <= 1e-12) : null;
    const rec: NodeRecord = {
      ...n,
      libraryExact: se.exact,
      cdSE: se.cd,
      levels,
      judgement,
      nu: { levels: nuLevels, judgement: nuJudgement },
      nuConverged,
      nuAgrees,
      exactHolds,
      commit,
    };
    appendFileSync(NODES_FIX, JSON.stringify(rec) + '\n');
    fixedNodes.set(n.key, rec);
  }
  const stops = [...fixedNodes.values()].filter((n) => n.exactHolds === false || n.nuAgrees === false);
  out.push('## The 4 nodes, re-run', '', '| node | half-angle | b | Mach | was | now | nu run |', '| --- | --- | --- | --- | --- | --- | --- |');
  for (const n of fixedNodes.values()) {
    const old = nodes.find((x) => x.key === n.key)!;
    out.push(
      `| ${n.key.replaceAll('|', '/')} | ${n.theta} | ${n.bevel.toFixed(4)} | ${n.mach} | ${old.judgement.why} | ${n.judgement.why}${n.judgement.pass ? `, eps ${(100 * n.judgement.value!).toFixed(4)}%` : ''} | ${n.nuConverged ? (n.nuAgrees ? 'converges and agrees' : 'converges and DISAGREES') : n.nu.judgement.why} |`,
    );
  }
  out.push('');
  if (stops.length > 0) {
    out.push('- **The runs stop (9.4 or 9.12) for a report.**', '');
    writeFileSync(join(here, 'shock-fix.out'), out.join('\n'));
    throw new Error('a re-run node breaks the exact-node rule or the nu agreement');
  }

  // The cells, before and after.
  const before = new Map(nodes.map((n) => [n.key, n]));
  const after = new Map(before);
  for (const n of fixedNodes.values()) after.set(n.key, n);
  const cellsBefore = candidateCells(before);
  const cellsAfter = candidateCells(after);
  const keyOf = (c: { i: number; j: number; k: number }) => `${c.i}|${c.j}|${c.k}`;
  const beforeKeys = new Set(cellsBefore.map(keyOf));
  const afterByKey = new Map(cellsAfter.map((c) => [keyOf(c), c]));
  const newCells = cellsAfter.filter((c) => !beforeKeys.has(keyOf(c)));
  const lostCells = cellsBefore.filter((c) => !afterByKey.has(keyOf(c)));

  // The check points: the 7 re-run, and those 9.6 gives the new cells.
  const CHECKS_FIX = join(here, 'shock-fix-checks.jsonl');
  const fixedChecks = new Map(readJsonl<CheckRecord & { commit: string }>(CHECKS_FIX).map((c) => [c.id, c]));
  const newKeys = new Set(newCells.map(keyOf));
  const newPoints: CheckPoint[] = [
    ...populationCheckPoints(newKeys),
    ...newCells.map((c) => ({
      id: `centre-${c.i}-${c.j}-${c.k}`,
      kind: 'centre' as const,
      theta: 0.5 * (THETA[c.i]! + THETA[c.i + 1]!),
      bevel: Math.exp(0.5 * (Math.log(BEVEL[c.j]!) + Math.log(BEVEL[c.j + 1]!))),
      mach: 0.5 * (MACH[c.k]! + MACH[c.k + 1]!),
      cell: [c.i, c.j, c.k] as const,
    })),
  ];
  const rerun = checks.filter((c) => shockFailed(c.levels));
  for (const p of [...rerun, ...newPoints]) {
    if (fixedChecks.has(p.id)) continue;
    const cell = afterByKey.get(p.cell.join('|'));
    if (cell === undefined) continue; // its cell is no longer a candidate: nothing to judge
    const rec = checkRecord({ id: p.id, kind: p.kind, theta: p.theta, bevel: p.bevel, mach: p.mach, cell: p.cell }, cell, commit);
    appendFileSync(CHECKS_FIX, JSON.stringify(rec) + '\n');
    fixedChecks.set(p.id, rec);
  }

  // All the check points together: the old ones with the 7 replaced, and the new ones.
  const all = [...checks.filter((c) => !fixedChecks.has(c.id)), ...fixedChecks.values()].filter((c) =>
    afterByKey.has(c.cell.join('|')),
  );
  const failing = all.filter((c) => !c.judgement.pass);
  const outside = all.filter((c) => c.inside === false);
  const removed = new Set(failing.map((c) => c.cell.join('|')));
  const servedBefore = cellsBefore.filter((c) => !new Set(checks.filter((x) => !x.judgement.pass).map((x) => x.cell.join('|'))).has(keyOf(c)));
  const servedAfter = cellsAfter.filter((c) => !removed.has(keyOf(c)));
  const servedBeforeKeys = new Set(servedBefore.map(keyOf));
  const servedAfterKeys = new Set(servedAfter.map(keyOf));
  out.push(
    '## The check points re-run and added',
    '',
    '| check point | kind | half-angle | b | Mach | was | now | its band | inside |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  );
  for (const c of fixedChecks.values()) {
    const old = checks.find((x) => x.id === c.id);
    out.push(
      `| ${c.id} | ${c.kind} | ${c.theta.toFixed(3)} | ${c.bevel.toFixed(4)} | ${c.mach.toFixed(3)} | ${old ? old.judgement.why : '(new)'} | ${c.judgement.why}${c.judgement.pass ? `, eps ${(100 * c.judgement.value!).toFixed(4)}% +- ${c.judgement.U!.toExponential(1)}` : ''} | ${c.epsLo.toFixed(3)} to ${c.epsHi.toFixed(3)} | ${c.inside === null ? '-' : c.inside ? 'yes' : 'NO'} |`,
    );
  }
  out.push(
    '',
    '## The cells',
    '',
    `- candidate cells: ${cellsBefore.length} before, ${cellsAfter.length} after (${newCells.length} new: ${newCells.map(keyOf).join(', ') || 'none'}; lost: ${lostCells.length})`,
    `- check points: ${all.length}; failing 9.5: ${failing.length} (${((100 * failing.length) / all.length).toFixed(2)}%, the cap is 2%); converged outside their band: ${outside.length}`,
    `- served cells (if the independent check passes): ${servedBefore.length} before, ${servedAfter.length} after; added: ${[...servedAfterKeys].filter((x) => !servedBeforeKeys.has(x)).join(', ') || 'none'}; removed: ${[...servedBeforeKeys].filter((x) => !servedAfterKeys.has(x)).join(', ') || 'none'}`,
    outside.length > 0
      ? '- **A converged check point lies outside its band: by 9.6 everything is refused.**'
      : failing.length > 0.02 * all.length
        ? '- **More than 2% of the check points fail 9.5: by 9.6 everything is refused.**'
        : '- 9.6 holds: no converged check point outside its band, and failures under 2%.',
    '',
  );
  writeFileSync(join(here, 'shock-fix.out'), out.join('\n'));
});
