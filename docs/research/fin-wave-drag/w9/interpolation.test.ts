/**
 * The comparison behind 0009 section 9's note of 2026-10-30 on the trace's
 * interpolation: eps on six hexagons at the five levels, with nu
 * interpolated along the rear corner's C+ characteristic (as 9.2 registers)
 * and with the pressure interpolated instead (nu then from the pressure and
 * K(psi)). A comparison put to the owner, not a run of the family. Writes
 * interpolation.out beside this file.
 *
 *   ONLY=./interpolation.test.ts npx vitest run --config docs/research/fin-wave-drag/w9/vitest.config.ts
 */

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import { exactSectionDrag } from '../../../../src/fins/section-drag';
import { hexagonal } from '../../../../src/fins/section';
import { hexagonCharacteristics, type TraceInterpolation } from '../../../../src/validation/planar-characteristics';

const here = dirname(fileURLToPath(import.meta.url));
const DEG = Math.PI / 180;
const CASES: readonly [number, number, number][] = [
  [8, 0.0179, 1.51],
  [12, 0.01, 1.6],
  [15, 0.01, 1.7],
  [5, 0.01, 3.0],
  [15, 0.1, 3.0],
  [Math.atan(0.04 / 0.15) / DEG, 0.15, 2.0],
];
const LEVELS = [16, 32, 64, 128, 256, 512];

test('the trace interpolated in nu and in the pressure', () => {
  const commit = execSync('git rev-parse --short HEAD', { cwd: here }).toString().trim();
  const out = [
    '# The trace interpolated in nu (registered) and in the pressure (generated by interpolation.test.ts; do not edit)',
    '',
    `- commit ${commit}; eps = cd / cd_SE - 1 at N = ${LEVELS.join(', ')} (512 beyond the registered levels, for this comparison only)`,
    '',
    '| half-angle, b, M | interpolation | eps at each N |',
    '| --- | --- | --- |',
  ];
  for (const [t, b, m] of CASES) {
    const se = exactSectionDrag(hexagonal(2 * b * Math.tan(t * DEG), b), m, { neglectReflectedWaves: true });
    for (const interpolation of ['nu', 'pressure'] as TraceInterpolation[]) {
      const eps = LEVELS.map((N) => hexagonCharacteristics(m, t * DEG, b, N, { interpolation }).cd / se.cd - 1);
      out.push(`| ${t.toFixed(3)} deg, ${b}, ${m} | ${interpolation} | ${eps.map((e) => e.toExponential(6)).join(', ')} |`);
    }
  }
  out.push('');
  writeFileSync(join(here, 'interpolation.out'), out.join('\n'));
});
