/**
 * The check that a solve of paired.test.ts resumed from its checkpoint
 * follows the same iterates, to the bit, as one never stopped: K1's
 * hexagon and K5's reference at level 1, each solved once without a stop
 * and once stopped after every save (a save after every 100 iterations)
 * and resumed, the final drags, residuals, iteration counts and conserved
 * variables compared exactly. Writes paired-resume.out.
 *
 *   ONLY=./paired-resume.test.ts npx vitest run --config docs/research/fin-wave-drag/w9/vitest.config.ts
 */

import { execSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import {
  P_CASES,
  freeStream,
  gridFrom,
  referenceInflow,
  referenceStart,
  sectionOf,
  shockExpansionState,
  solveEuler,
  type Primitive,
  type SolveResult,
} from './paired';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../../..');

test('W9(a): a resumed solve is the same to the bit', () => {
  const commit = execSync('git rev-parse --short HEAD', { cwd: here }).toString().trim();
  const dir = join(root, 'tests/tmp-w9/checkpoints-check');
  mkdirSync(dir, { recursive: true });
  const out = ['# A resumed solve against one never stopped (generated by paired-resume.test.ts)', '', `- commit ${commit}`, ''];
  let allSame = true;
  const level = 1;
  const cases: [string, string][] = [
    ['K1', 'hexagon'],
    ['K5', 'reference'],
  ];
  for (const [name, kind] of cases) {
    const c = P_CASES[name]!;
    const section = sectionOf(c.theta, c.bevel);
    let from = 0;
    let inflow: Primitive = freeStream(c.mach);
    if (kind === 'reference') {
      const se = shockExpansionState(c.theta, c.bevel, c.mach);
      const start = referenceStart(section, c.bevel, level);
      from = start.column;
      inflow = referenceInflow(c.theta, c.mach, se.p2, se.Kshock * 1.05).state;
    }
    const whole = solveEuler(gridFrom(section, level, from), inflow, c.mach, level);
    const path = join(dir, `${name}-${kind}.bin`);
    rmSync(path, { force: true });
    let stops = 0;
    let resumed: SolveResult | undefined;
    while (resumed === undefined) {
      try {
        resumed = solveEuler(gridFrom(section, level, from), inflow, c.mach, level, { path, everySeconds: 0, abortAfterSave: true });
      } catch (e) {
        if (!(e instanceof Error) || !e.message.startsWith('aborted after a save')) throw e;
        stops++;
      }
    }
    rmSync(path, { force: true });
    const a = whole.solver.conserved();
    const b = resumed.solver.conserved();
    let differing = a.length === b.length ? 0 : -1;
    for (let i = 0; i < a.length && differing >= 0; i++) if (a[i] !== b[i]) differing++;
    const same =
      differing === 0 &&
      whole.cd === resumed.cd &&
      whole.residual === resumed.residual &&
      whole.iterations === resumed.iterations &&
      resumed.resumed === stops;
    allSame &&= same;
    out.push(
      `- ${name} ${kind}, level ${level}: ${whole.iterations} iterations; stopped and resumed ${stops} times; drag ${whole.cd} and ${resumed.cd}; residual ${whole.residual} and ${resumed.residual}; conserved values differing: ${differing}: ${same ? 'the same to the bit' : 'DIFFERENT'}`,
    );
  }
  out.push('', `- ${allSame ? 'a resumed solve is the same to the bit' : 'A RESUMED SOLVE DIFFERS: the runs must not rely on checkpoints'}`, '');
  writeFileSync(join(here, 'paired-resume.out'), out.join('\n'));
  if (!allSame) throw new Error('a resumed solve differs');
});
