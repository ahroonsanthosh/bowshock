/**
 * 0009 section 9.15's exactness check of the profile inflow, before any
 * case: a parallel rotational flow at uniform pressure, on the
 * reference's columns and rows at levels 2 and 3 for K1 (b 0.08) and E2
 * (b 0.12) with the wall held at the flat's height throughout, the inflow a
 * faceStates boundary with one state per row (pressure p2, flow along x,
 * the free stream's total enthalpy, an entropy varying with the row: a
 * layer at the wall and a streak in the stream), every cell started from
 * its row's state. After 1,000 iterations of the reference's scheme the
 * largest relative change of density, x velocity and pressure, and the
 * largest |v| over the speed, must each be at most 1e-12. Writes
 * last-exact.out.
 *
 *   ONLY=./last-exact.test.ts npx vitest run --config docs/research/fin-wave-drag/w9/vitest.config.ts
 */

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import {
  P_CASES,
  gridFrom,
  gridLines,
  makeSolver,
  referenceInflow,
  referenceStart,
  sectionOf,
  shockExpansionState,
  type Primitive,
} from './paired';

const here = dirname(fileURLToPath(import.meta.url));

test("W9(a): 9.15's profile inflow holds a parallel rotational flow", () => {
  const commit = execSync('git rev-parse --short HEAD', { cwd: here }).toString().trim();
  const out = [
    "# 0009 section 9.15: the profile inflow's exactness check (generated by last-exact.test.ts; do not edit)",
    '',
    `- commit ${commit}; 1,000 iterations; the bound 1e-12 on each measure`,
    '',
    '| case | level | grid | rows | entropy over K_shock, wall row to top | density | x velocity | pressure | v over speed | passes |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  let all = true;
  for (const name of ['K1', 'E2']) {
    const c = P_CASES[name]!;
    const section = sectionOf(c.theta, c.bevel);
    const se = shockExpansionState(c.theta, c.bevel, c.mach);
    for (const level of [2, 3]) {
      const start = referenceStart(section, c.bevel, level);
      const grid = gridFrom(section, level, start.column, true);
      const { nj } = gridLines(section, level);
      // A layer at the wall a few rows thick, as the hexagon's, and a streak in the stream.
      const K = Array.from({ length: nj }, (_, j) => {
        const eta = (j + 0.5) / nj;
        return se.Kshock * (1 + 0.06 * Math.exp(-(j + 0.5) / 1.5) + 0.02 * Math.exp(-(((eta - 0.4) / 0.05) ** 2)));
      });
      const rows: Primitive[] = K.map((k) => referenceInflow(c.theta, c.mach, se.p2, k).state);
      const s = makeSolver(grid, rows);
      s.iterate(1000);
      let dRho = 0;
      let dU = 0;
      let dP = 0;
      let v = 0;
      for (let j = 0; j < grid.nj; j++) {
        const w = rows[j]!;
        for (let i = 0; i < grid.ni; i++) {
          const q = s.primitive(i, j);
          dRho = Math.max(dRho, Math.abs(q.rho / w.rho - 1));
          dU = Math.max(dU, Math.abs(q.u / w.u - 1));
          dP = Math.max(dP, Math.abs(q.p / w.p - 1));
          v = Math.max(v, Math.abs(q.v) / w.u);
        }
      }
      const ok = dRho <= 1e-12 && dU <= 1e-12 && dP <= 1e-12 && v <= 1e-12;
      all &&= ok;
      out.push(
        `| ${name} | ${level} | ${grid.ni} x ${grid.nj} | ${nj} | ${(K[0]! / se.Kshock).toFixed(4)} to ${(K[nj - 1]! / se.Kshock).toFixed(4)} (streak ${(Math.max(...K.slice(2)) / se.Kshock).toFixed(4)}) | ${dRho.toExponential(2)} | ${dU.toExponential(2)} | ${dP.toExponential(2)} | ${v.toExponential(2)} | ${ok ? 'yes' : 'NO'} |`,
      );
    }
  }
  out.push('', `- ${all ? 'passes: the profile inflow holds the parallel flow to round-off' : 'FAILS: no case may run'}`, '');
  writeFileSync(join(here, 'last-exact.out'), out.join('\n'));
  if (!all) throw new Error('the exactness check of 9.15 fails');
});
