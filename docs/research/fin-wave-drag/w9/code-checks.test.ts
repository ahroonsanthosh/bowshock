/**
 * The record of 0009 section 9.3's code checks, T1 to T5, with every number
 * (the committed test, tests/validation/planar-characteristics.test.ts,
 * asserts the same predicates). Writes code-checks.out beside this file.
 *
 *   ONLY=./code-checks.test.ts npx vitest run --config docs/research/fin-wave-drag/w9/vitest.config.ts
 */

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import {
  LEVELS,
  PAIRS,
  T2_CASES,
  analyticReflection,
  convergesAsRegistered,
  exactLanding,
  hexagonEps,
  methodLanding,
  methodReflection,
  quadratureCheck,
  shearFlow,
  t1,
  t4Passes,
} from '../../../../tests/support/planar-characteristics-checks';

const here = dirname(fileURLToPath(import.meta.url));
const e = (v: number) => v.toExponential(3);

test('0009 section 9.3: T1 to T5, recorded', () => {
  const commit = execSync('git rev-parse --short HEAD', { cwd: here }).toString().trim();
  const dirty = execSync('git status --porcelain -- ../../../../src', { cwd: here }).toString().trim() !== '';
  const out: string[] = [
    '# 0009 section 9.3: the code checks (generated by code-checks.test.ts; do not edit)',
    '',
    `- commit ${commit}${dirty ? ' (with uncommitted changes under src)' : ''}; levels N = ${LEVELS.join(', ')}`,
    '',
  ];
  let all = true;

  out.push('## T1: wedge over 0.1 of the chord and a flat to a square trailing edge', '');
  out.push('| theta, M | largest |drag / library - 1| | largest |flat p / library - 1| | pass (both within 1e-12) |', '| --- | --- | --- | --- |');
  for (const [t, m] of PAIRS) {
    const r = LEVELS.map((N) => t1(t, m, N));
    const drag = Math.max(...r.map((x) => x.drag));
    const flat = Math.max(...r.map((x) => x.flatPressure));
    const pass = drag <= 1e-12 && flat <= 1e-12;
    all &&= pass;
    out.push(`| ${t} deg, ${m} | ${e(drag)} | ${e(flat)} | ${pass} |`);
  }

  out.push('', '## T2: hexagons the library calls exact, eps at every level', '');
  out.push('| t/c, bevel, M | library exact | eps at N = 16 .. 256 | pass (all within 1e-12) |', '| --- | --- | --- | --- |');
  for (const c of T2_CASES) {
    const r = LEVELS.map((N) => hexagonEps(c.tc, c.bevel, c.mach, N));
    const pass = r.every((x) => x.exact && Math.abs(x.eps) <= 1e-12);
    all &&= pass;
    out.push(`| ${c.tc}, ${c.bevel}, ${c.mach} | ${r[0]!.exact} | ${r.map((x) => e(x.eps)).join(', ')} | ${pass} |`);
  }

  out.push('', '## T3: the first reflection against R = (Q - sigma) / (Q + sigma)', '');
  out.push('| theta, M | R | R_N at N = 16 .. 256 | |R_N - R| | pass |', '| --- | --- | --- | --- | --- |');
  for (const [t, m] of PAIRS) {
    const R = analyticReflection(t, m);
    const rn = LEVELS.map((N) => methodReflection(t, m, N));
    const err = rn.map((v) => v - R);
    // Decreasing from N = 32 to 256, the last at most a sixth of N = 32's, or all below 1e-10.
    const pass = convergesAsRegistered(err.slice(1), err[1]!, 1 / 6, 1e-10);
    all &&= pass;
    out.push(`| ${t} deg, ${m} | ${R.toFixed(6)} | ${rn.map((v) => v.toFixed(6)).join(', ')} | ${err.map((v) => e(Math.abs(v))).join(', ')} | ${pass} |`);
  }

  out.push('', '## T4: the parallel shear flow (p = 1, theta = 0, ln K to 0.044), and its four planted errors', '');
  out.push('| code | largest |p - 1| at N = 16 .. 256 | largest |theta| | mass balance | passes T4 |', '| --- | --- | --- | --- | --- |');
  const variants: { name: string; planted?: 'no-entropy-term' | 'entropy-term-sign' | 'previous-k'; mirror?: boolean }[] = [
    { name: 'as written' },
    { name: 'planted: the entropy term left out', planted: 'no-entropy-term' },
    { name: 'planted: its sign flipped', planted: 'entropy-term-sign' },
    { name: 'planted: K looked up at psi measured from the top', mirror: true },
    { name: 'planted: each point given the K of the point before it on its C- line', planted: 'previous-k' },
  ];
  for (const v of variants) {
    const levels = LEVELS.map((N) => shearFlow(N, { ...(v.planted ? { planted: v.planted } : {}), ...(v.mirror ? { mirror: true } : {}) }));
    const pass = t4Passes(levels);
    // The code as written must pass; every planted error must fail.
    all &&= v.name === 'as written' ? pass : !pass;
    out.push(
      `| ${v.name} | ${levels.map((l) => (l.failure ? 'failed' : e(l.p))).join(', ')} | ${levels.map((l) => (l.failure ? 'failed' : e(l.th))).join(', ')} | ${levels.map((l) => (l.failure ? `failed (${l.failure})` : e(l.mass))).join(', ')} | ${pass} |`,
    );
  }

  out.push('', '## T5: the landing of the C- line from P against its exact place (bevel 0.1)', '');
  out.push('| theta, M | exact landing | |error| at N = 16 .. 256 | pass |', '| --- | --- | --- | --- |');
  for (const [t, m] of PAIRS) {
    const exact = exactLanding(t, m);
    const check = Math.abs(exactLanding(t, m, 128) - exact);
    const err = LEVELS.map((N) => methodLanding(t, m, N) - exact);
    // Decreasing from N = 32 to 256, the last at most a twelfth of N = 64's.
    const pass = convergesAsRegistered(err.slice(1), err[2]!, 1 / 12, 1e-12) && check < 1e-12;
    all &&= pass;
    out.push(`| ${t} deg, ${m} | ${exact.toFixed(12)} (quadrature checked to ${e(check)}) | ${err.map((v) => e(Math.abs(v))).join(', ')} | ${pass} |`);
  }
  const q = quadratureCheck();
  const qPass = Math.abs(q.method / q.exact - 1) <= 1e-14;
  all &&= qPass;
  out.push('', `- the rear bevel's quadrature on a planted linear Cp: ${q.method} against ${q.exact}, relative ${e(Math.abs(q.method / q.exact - 1))}: ${qPass}`);
  out.push('', `- every check as registered: ${all}`, '');
  writeFileSync(join(here, 'code-checks.out'), out.join('\n'));
});
