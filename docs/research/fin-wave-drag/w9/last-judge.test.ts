/**
 * The verdict of 0009 section 9.15, the last Euler check, from the records
 * of last.test.ts (last.jsonl, last-walls/) and the cells after 9.14's
 * re-judgement (nodes.jsonl with shock-fix-nodes.jsonl, checks.jsonl with
 * shock-fix-checks.jsonl). The rule and the verdict tree are 9.13's (as in
 * paired-judge.test.ts); 9.15 adds the gated prediction that the
 * reference's own bevel deviation from p3 shrinks from level 2 to 3 to 4,
 * and records it beside the hexagon's deviation from the method. Computes
 * no new solve. Writes last-verdict.out and, where the verdict serves,
 * served-cells.json. Written before any solve of levels 2 to 4 was run.
 *
 *   ONLY=./last-judge.test.ts npx vitest run --config docs/research/fin-wave-drag/w9/vitest.config.ts
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import { BEVEL, DEG, MACH, THETA, candidateCells, readJsonl, type Cell, type NodeRecord } from './family';
import { GAMMA, P_CASES, P_NAMES, bevelWindow, flatWindow, type WallFace } from './paired';

const here = dirname(fileURLToPath(import.meta.url));
const e = (v: number | null | undefined, d = 3) => (v === null || v === undefined || Number.isNaN(v) ? '-' : v.toExponential(d));

type Pt = { readonly x: number; readonly p: number };
const at = (pts: readonly Pt[], x: number) => {
  for (let i = 0; i + 1 < pts.length; i++) {
    const u = pts[i]!;
    const v = pts[i + 1]!;
    if (x >= u.x && x <= v.x) return v.x === u.x ? u.p : u.p + ((v.p - u.p) * (x - u.x)) / (v.x - u.x);
  }
  throw new RangeError(`x = ${x} is outside the method's wall points`);
};
/** Trapezoid integral of (p - c) over [a, b] on a wall list. */
const integral = (pts: readonly Pt[], a: number, b: number, c: number) => {
  const xs = [a, ...pts.map((q) => q.x).filter((x) => x > a && x < b), b];
  let s = 0;
  for (let i = 0; i + 1 < xs.length; i++) s += 0.5 * (at(pts, xs[i]!) - c + at(pts, xs[i + 1]!) - c) * (xs[i + 1]! - xs[i]!);
  return s;
};

interface MethodRecord {
  readonly cdSE: number;
  readonly p2: number;
  readonly p3: number;
  readonly Kshock: number;
  readonly eps256: number;
  readonly epsNode: number | null;
  readonly landing: number;
  readonly flat128: Pt[];
  readonly bevel128: Pt[];
  readonly flat256: Pt[];
  readonly bevel256: Pt[];
}
interface Line {
  readonly case: string;
  readonly kind: 'hexagon' | 'reference';
  readonly level: number;
  readonly converged: boolean;
  readonly iterations: number;
  readonly cd: number;
  readonly same913?: boolean | null;
  readonly column?: number;
  readonly rowsAboveKshock?: number[];
  readonly rowsCarried?: number[];
  readonly Kmax?: number;
}
type Status = 'agreement' | 'disagreement' | 'unresolved';

/** 9.13's uncertainty and rule for one window from D_2, D_3, D_4 (as paired-judge.test.ts). */
function judgeWindow(D: readonly number[], G: number, UM: number, capped: boolean) {
  const [D2, D3, D4] = [D[2]!, D[3]!, D[4]!];
  const d3 = D3 - D2;
  const d4 = D4 - D3;
  let Dstar = NaN;
  let UE = NaN;
  let why: string;
  let status: Status;
  if (capped) {
    status = 'unresolved';
    why = 'a solve stopped at the cap';
  } else if (!(Math.abs(d4) < Math.abs(d3))) {
    status = 'unresolved';
    why = `|d_4| ${e(Math.abs(d4))} >= |d_3| ${e(Math.abs(d3))}`;
  } else {
    if (d3 * d4 > 0) {
      Dstar = D4 + d4 / (2 * (Math.SQRT2 - 1));
      UE = Math.abs(d4) / (2 * (Math.SQRT2 - 1));
    } else {
      Dstar = D4;
      UE = 2.5 * Math.abs(d4);
    }
    const tol = Math.max(UE + UM, Math.abs(G) / 4);
    if (!(UE <= Math.abs(G) / 4)) {
      status = 'unresolved';
      why = `U_E ${e(UE)} > |G| / 4 ${e(Math.abs(G) / 4)}`;
    } else if (Math.abs(Dstar) <= tol) {
      status = 'agreement';
      why = `|D*| ${e(Math.abs(Dstar))} <= ${e(tol)}`;
    } else {
      status = 'disagreement';
      why = `|D*| ${e(Math.abs(Dstar))} > ${e(tol)}`;
    }
  }
  return { d3, d4, Dstar, UE, status, why };
}

test("W9(a): 9.15's verdict", () => {
  const out: string[] = ['# W9(a): the verdict of 0009 section 9.15, the last Euler check (generated by last-judge.test.ts; do not edit)', ''];
  const lines = readJsonl<Line>(join(here, 'last.jsonl'));
  const line = (c: string, kind: string, level: number) => lines.filter((l) => l.case === c && l.kind === kind && l.level === level).at(-1);
  const walls = (c: string, kind: string, level: number) =>
    JSON.parse(readFileSync(join(here, 'last-walls', `${c}-${kind}-L${level}.json`), 'utf8')) as WallFace[];

  // The hexagons against 9.13's: the same wall pressures to the bit (9.15: then the flat windows carry over).
  const hexLines = lines.filter((l) => l.kind === 'hexagon');
  const differ = hexLines.filter((l) => l.same913 === false);
  out.push(
    "## The hexagons against 9.13's solves",
    '',
    `- hexagon solves recorded: ${hexLines.length}; wall pressures equal to 9.13's to the bit: ${hexLines.filter((l) => l.same913 === true).length}; different: ${differ.map((l) => `${l.case} level ${l.level}`).join(', ') || 'none'}; ${differ.length === 0 ? "the flat windows are the same arithmetic as 9.13's" : 'the flat windows are judged again from these solves'}`,
    '',
  );

  const results: Record<string, { bevel: Status; flat: Status } | null> = {};
  let complete = true;
  for (const name of P_NAMES) {
    const c = P_CASES[name]!;
    out.push(`## ${name}: ${c.theta} deg, b ${c.bevel.toFixed(4)}, Mach ${c.mach}`, '');
    const mFile = join(here, 'last-walls', `${name}-method.json`);
    if (!existsSync(mFile)) {
      out.push('- the method is not recorded', '');
      results[name] = null;
      complete = false;
      continue;
    }
    const m = JSON.parse(readFileSync(mFile, 'utf8')) as MethodRecord;
    const q = 0.5 * GAMMA * c.mach * c.mach;
    const tan = Math.tan(c.theta * DEG);
    const scale = 2 / (q * m.cdSE);
    const [w0, w1] = bevelWindow(c.bevel);
    const [f0, f1] = flatWindow(m.landing, c.bevel);
    const G256 = scale * -tan * integral(m.bevel256, w0, w1, m.p3);
    const G128 = scale * -tan * integral(m.bevel128, w0, w1, m.p3);
    const UMb = 2 * Math.abs(G256 - G128) + 1e-6;
    out.push(
      `- the method: eps ${(100 * m.eps256).toFixed(4)}% at N = 256 (the node's ${m.epsNode === null ? '-' : (100 * m.epsNode).toFixed(4) + '%'}); first landing ${m.landing.toFixed(4)}; bevel window [${w0.toFixed(4)}, ${w1.toFixed(4)}], G ${e(G256)} of the drag, U_M ${e(UMb)}; flat window [${f0.toFixed(4)}, ${f1.toFixed(4)}]`,
      '',
      '| level | hexagon | reference | rows carried (K_hex > K_shock), largest K_hex / K_shock | E_k | H_k (unpaired) | H_k - G | R_k, the reference against p3 | D_k bevel | F_k | G_k | D_k flat | same as 9.13 |',
      '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    );
    const Db: number[] = [];
    const Df: number[] = [];
    const R: number[] = [];
    let Gflat = NaN;
    let UMf = NaN;
    let capped = false;
    let caseComplete = true;
    for (const k of [0, 1, 2, 3, 4]) {
      const h = line(name, 'hexagon', k);
      const r = line(name, 'reference', k);
      if (h === undefined || r === undefined) {
        out.push(`| ${k} | ${h ? 'done' : 'not run'} | ${r ? 'done' : 'not run'} | | | | | | | | | | |`);
        if (k >= 2) caseComplete = false;
        continue;
      }
      if (k >= 2 && (!h.converged || !r.converged)) capped = true;
      const hf = walls(name, 'hexagon', k);
      const rf = walls(name, 'reference', k);
      const off = r.column!;
      let E = 0;
      let H = 0;
      let Rk = 0;
      for (let i = 0; i < hf.length; i++) {
        const f = hf[i]!;
        if (!(f.y > 0 && f.x > 1 - c.bevel && f.x >= w0 && f.x <= w1)) continue;
        const g = rf[i - off]!;
        if (!(Math.abs(g.x - f.x) <= 1e-12 && Math.abs(g.length - f.length) <= 1e-12)) {
          throw new Error(`${name} level ${k}: the hexagon's and the reference's faces do not match at x = ${f.x}`);
        }
        E += (f.p - g.p) * f.nx * f.length;
        H += (f.p - m.p3) * f.nx * f.length;
        Rk += (g.p - m.p3) * g.nx * g.length;
      }
      E *= scale;
      H *= scale;
      Rk *= scale;
      const flat = hf.filter((f) => f.y > 0 && f.x >= f0 && f.x <= f1);
      const L = flat.reduce((a, f) => a + f.length, 0);
      const F = flat.reduce((a, f) => a + (f.p - m.p2) * f.length, 0) / L;
      const Gk = flat.reduce((a, f) => a + (at(m.flat256, f.x) - m.p2) * f.length, 0) / L;
      if (k === 4) {
        Gflat = Gk;
        const G128f = flat.reduce((a, f) => a + (at(m.flat128, f.x) - m.p2) * f.length, 0) / L;
        UMf = 2 * Math.abs(Gk - G128f) + 1e-6;
      }
      Db[k] = E - G256;
      Df[k] = F - Gk;
      R[k] = Rk;
      const carried = r.rowsCarried ?? [];
      out.push(
        `| ${k} | ${h.iterations}${h.converged ? '' : ' (CAP)'} | ${r.iterations}${r.converged ? '' : ' (CAP)'} | ${carried.length} rows (${carried.slice(0, 6).join(', ')}${carried.length > 6 ? ', ...' : ''}), ${(h.Kmax! / m.Kshock).toFixed(5)} | ${e(E)} | ${e(H)} | ${e(H - G256)} | ${e(Rk)} | ${e(Db[k])} | ${e(F)} | ${e(Gk)} | ${e(Df[k])} | ${h.same913 === null || h.same913 === undefined ? '-' : h.same913 ? 'yes' : 'NO'} |`,
      );
    }
    out.push('');
    if (!caseComplete) {
      out.push('- levels 2 to 4 are not all recorded: not judged', '');
      results[name] = null;
      complete = false;
      continue;
    }
    // 9.15's gated prediction (i): the reference's own deviation shrinks from level 2 to 3 to 4.
    const shrinks = Math.abs(R[2]!) > Math.abs(R[3]!) && Math.abs(R[3]!) > Math.abs(R[4]!);
    let jb = judgeWindow(Db, G256, UMb, capped);
    if (!shrinks) jb = { ...jb, status: 'unresolved', why: `prediction (i) fails: |R_k| ${e(Math.abs(R[2]!))}, ${e(Math.abs(R[3]!))}, ${e(Math.abs(R[4]!))} does not shrink (${jb.status} by the rule alone: ${jb.why})` };
    const jf = judgeWindow(Df, Gflat, UMf, capped);
    out.push(
      `- prediction (i), gated: |R_k| at levels 2, 3, 4: ${e(Math.abs(R[2]!))}, ${e(Math.abs(R[3]!))}, ${e(Math.abs(R[4]!))}: ${shrinks ? 'shrinks' : 'DOES NOT SHRINK'}`,
      `- prediction (ii), recorded: R_k against H_k - G at levels 2, 3, 4 in the table above`,
      `- bevel: G ${e(G256)}, U_M ${e(UMb)}; d_3 ${e(jb.d3)}, d_4 ${e(jb.d4)}; D* ${e(jb.Dstar)}, U_E ${e(jb.UE)}: **${jb.status}** (${jb.why})`,
      `- flat: G ${e(Gflat)}, U_M ${e(UMf)}; d_3 ${e(jf.d3)}, d_4 ${e(jf.d4)}; D* ${e(jf.Dstar)}, U_E ${e(jf.UE)}: **${jf.status}** (${jf.why})`,
      '',
    );
    results[name] = { bevel: jb.status, flat: jf.status };
  }

  // The cells after 9.14's re-judgement.
  const nodes = new Map(readJsonl<NodeRecord>(join(here, 'nodes.jsonl')).map((n) => [n.key, n]));
  for (const n of readJsonl<NodeRecord>(join(here, 'shock-fix-nodes.jsonl'))) nodes.set(n.key, n);
  const cells = candidateCells(nodes);
  type C = { id: string; cell: number[]; judgement: { pass: boolean }; inside: boolean | null };
  const fixed = new Map(readJsonl<C>(join(here, 'shock-fix-checks.jsonl')).map((x) => [x.id, x]));
  const keys = new Set(cells.map((x) => `${x.i}|${x.j}|${x.k}`));
  const checks = [...readJsonl<C>(join(here, 'checks.jsonl')).filter((x) => !fixed.has(x.id)), ...fixed.values()].filter((x) =>
    keys.has(x.cell.join('|')),
  );
  const removed = new Set(checks.filter((x) => !x.judgement.pass).map((x) => x.cell.join('|')));
  const served = cells.filter((x) => !removed.has(`${x.i}|${x.j}|${x.k}`));
  const nearZero = (x: Cell) => x.corners.every((n) => Math.abs(n.judgement.value!) + n.judgement.U! < 5e-4);
  const below = (x: Cell) => MACH[x.k + 1]! < 2.2 - 1e-9;
  const fallback = served.filter((x) => below(x) || nearZero(x));
  out.push(
    '## The cells (9.6 after 9.14)',
    '',
    `- candidate cells ${cells.length}; check points ${checks.length}, failing 9.5 ${checks.filter((x) => !x.judgement.pass).length}, outside their band ${checks.filter((x) => x.inside === false).length}; served if the check passes: ${served.length}; with K5 unresolved: ${fallback.length} (${served.filter(below).length} with every corner below Mach 2.2, ${served.filter((x) => !below(x) && nearZero(x)).length} near zero at Mach 2.2 and above)`,
    '',
  );

  // The verdict (9.13's tree; 9.15 is the last look).
  const all = Object.values(results);
  const statuses = all.flatMap((r) => (r === null ? [] : [r.bevel, r.flat]));
  const four = ['K1', 'K2', 'K3', 'E2'].map((n) => results[n]);
  const fourAgree = four.every((r) => r !== null && r !== undefined && r.bevel === 'agreement' && r.flat === 'agreement');
  const k5 = results.K5;
  const k5Agrees = k5 !== null && k5 !== undefined && k5.bevel === 'agreement' && k5.flat === 'agreement';
  let servedCells: Cell[] = [];
  let verdict: string;
  if (statuses.includes('disagreement')) {
    verdict = 'the check FAILS: a resolved disagreement (above). Nothing is served, and by 9.15 W9(a) is closed with the refusal kept.';
  } else if (!complete) {
    verdict = 'not complete: levels 2 to 4 of every case are needed. Nothing is served yet.';
  } else if (fourAgree && k5Agrees) {
    servedCells = served;
    verdict = `the check passes in all five cases: ${served.length} cells are served (9.6 after 9.14), on the third design of the independent check.`;
  } else if (fourAgree) {
    servedCells = fallback;
    verdict = `K1, K2, K3 and E2 agree; K5 is unresolved: ${fallback.length} cells are served (every corner below Mach 2.2, or near zero), on the third design of the independent check; the other ${served.length - fallback.length} stay refused.`;
  } else {
    verdict = 'unresolved: a window of K1, K2, K3 or E2 is unresolved, and none disagrees. Nothing is served, and by 9.15 W9(a) is closed with the refusal kept.';
  }
  out.push('## Verdict', '', `- ${verdict}`, '');
  writeFileSync(join(here, 'last-verdict.out'), out.join('\n'));
  if (servedCells.length > 0) {
    writeFileSync(
      join(here, 'served-cells.json'),
      JSON.stringify({
        theta: THETA,
        bevel: BEVEL,
        mach: MACH,
        cells: servedCells.map((x) => ({ i: x.i, j: x.j, k: x.k, epsLo: Number(x.epsLo.toFixed(3)), epsHi: Number(x.epsHi.toFixed(3)) })),
      }),
    );
  }
});
