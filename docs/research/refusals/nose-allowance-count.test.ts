/**
 * How many of the audit's cases carry the nose's model-form allowance
 * (design record 0022 section 4.8 and section 9 step 7; 0014 10.7 (am)):
 * the cases whose nose the page serves (no nose reason) and whose family,
 * fineness and Mach number a measured box holds, as `noseModelAllowance`
 * decides it, split by whether the total is served. The cases are
 * impact.test.ts's own (the same population and the same draws). Nothing
 * here solves a nose, so the band's growth is given as the allowance a,
 * relative to each nose term; the C_D it adds is a times that term.
 * Writes out/nose-allowance-count.out. Run with
 * `ONLY=./nose-allowance-count.test.ts`.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import { noseModelAllowance } from '../../../src/app/nose-model-allowance';
import { MACH_BANDS, drawAltitude, mulberry32, population } from './population';
import { calibreBody, noseReasons, totalReasons } from './evaluate';

const here = dirname(fileURLToPath(import.meta.url));

test('the cases that carry the nose model-form allowance', () => {
  const rockets = population(2000);
  // impact.test.ts's evaluateAll, the same draws in the same order (seed 7).
  const rand = mulberry32(7);
  const rows: { band: number; total: boolean; a: number; mach: number; fineness: number; nose: string }[] = [];
  let noseServed = 0;
  let totals = 0;
  for (const rocket of rockets) {
    MACH_BANDS.forEach(([lo, hi], band) => {
      const mach = lo + (hi - lo) * (0.0005 + 0.999 * rand());
      const altitudeKm = drawAltitude(rand(), rand());
      const nose = noseReasons(rocket, mach);
      if (nose.length > 0) return;
      noseServed++;
      const total = totalReasons(rocket, { mach, altitudeKm }).length === 0;
      if (total) totals++;
      const a = noseModelAllowance(calibreBody(rocket).nose, mach);
      if (a !== null) {
        rows.push({ band, total, a: a.halfWidth, mach, fineness: rocket.noseFineness, nose: rocket.nose });
      }
    });
  }
  const lines = [
    '# Cases carrying the nose model-form allowance (generated by nose-allowance-count.test.ts; do not edit)',
    '',
    `- cases whose nose the page serves: ${noseServed} of 8000; totals served: ${totals}`,
    `- of those, inside a measured box: ${rows.length} (with a total served: ${rows.filter((r) => r.total).length})`,
    '',
    '| Band | Nose | Fineness | Mach | a | Total served |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map(
      (r) =>
        `| M ${MACH_BANDS[r.band]![0].toFixed(1)}-${MACH_BANDS[r.band]![1].toFixed(1)} | ${r.nose} | ` +
        `${r.fineness.toFixed(3)} | ${r.mach.toFixed(3)} | ${(100 * r.a).toFixed(1)}% | ${r.total ? 'yes' : 'no'} |`,
    ),
    '',
  ];
  writeFileSync(join(here, 'out', 'nose-allowance-count.out'), lines.join('\n'));
});
