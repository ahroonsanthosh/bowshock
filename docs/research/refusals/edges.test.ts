/**
 * The parameters the fin-edge work items of 0014 turn on, over the
 * population (./population.ts) at the conditions of the impact run: the
 * thin-layer parameter c / [h Re_c^(1/5)] of blunt trailing edges (TR 1109
 * fig. 29(a) is read to 4.5), the normal Mach number of rounded leading
 * edges (TN 2960's front-side band is set at 1.49 to 2.90), their Reynolds
 * number on the edge's diameter, and the trailing-edge half-angle of fins
 * at the base. Writes ./out/edges.out.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import { MACH_BANDS, atmosphere, drawAltitude, mulberry32, population } from './population';

const here = dirname(fileURLToPath(import.meta.url));
const N = Number(process.env.N_ROCKETS ?? 2000);

function quantiles(v: number[]): string {
  if (v.length === 0) return '-';
  const s = [...v].sort((a, b) => a - b);
  const at = (p: number) => s[Math.min(s.length - 1, Math.floor(p * s.length))]!;
  return [0.05, 0.25, 0.5, 0.75, 0.95].map((p) => at(p).toPrecision(3)).join(' / ');
}
const share = (v: number[], f: (x: number) => boolean) =>
  v.length === 0 ? '-' : `${((100 * v.filter(f).length) / v.length).toFixed(1)}%`;

test('fin-edge parameters over the population', () => {
  const rockets = population(N);
  const rand = mulberry32(7);
  const lines = ['# Fin-edge parameters (generated by edges.test.ts; do not edit)', ''];
  const rows: { band: number; x: number[]; mn: number[]; reD: number[] }[] = MACH_BANDS.map((_, band) => ({
    band,
    x: [],
    mn: [],
    reD: [],
  }));
  for (const r of rockets) {
    MACH_BANDS.forEach(([lo, hi], band) => {
      // The impact run's draws, in its order: Mach, then the altitude pair.
      const mach = lo + (hi - lo) * (0.0005 + 0.999 * rand());
      const altitude = drawAltitude(rand(), rand());
      const air = atmosphere(altitude);
      const rePerMetre = (air.rho * air.a * mach) / air.mu;
      const row = rows[band]!;
      if (r.section === 'rounded-le-square-te' || r.section === 'square-both' || r.section === 'bevel-le-square-te') {
        // Root chord: the longest, so the largest c / [h Re^(1/5)].
        row.x.push(r.rootChord / (r.thickness * (rePerMetre * r.rootChord) ** 0.2));
      }
      if (r.section === 'rounded-le-square-te' || r.section === 'rounded-both') {
        row.mn.push(mach * Math.cos((r.leadingEdgeSweepDeg * Math.PI) / 180));
        row.reD.push(rePerMetre * r.thickness);
      }
    });
  }
  lines.push(
    '## Blunt trailing edges: c / [h Re_c^(1/5)] at the root',
    '',
    '| Band | 5% / 25% / 50% / 75% / 95% | At most 1.0 (served today) | At most 4.5 (TR 1109 fig. 29(a) read) |',
    '| --- | --- | --- | --- |',
    ...rows.map((r) => `| M ${MACH_BANDS[r.band]![0]}-${MACH_BANDS[r.band]![1]} | ${quantiles(r.x)} | ${share(r.x, (x) => x <= 1)} | ${share(r.x, (x) => x <= 4.5)} |`),
    '',
    '## Rounded leading edges: normal Mach number M cos(sweep)',
    '',
    '| Band | 5% / 25% / 50% / 75% / 95% | Below 1 | 1 to 1.49 | 1.49 to 3.0 |',
    '| --- | --- | --- | --- | --- |',
    ...rows.map(
      (r) =>
        `| M ${MACH_BANDS[r.band]![0]}-${MACH_BANDS[r.band]![1]} | ${quantiles(r.mn)} | ${share(r.mn, (m) => m < 1)} | ${share(r.mn, (m) => m >= 1 && m < 1.49)} | ${share(r.mn, (m) => m >= 1.49)} |`,
    ),
    '',
    '## Rounded leading edges: Reynolds number on the edge diameter',
    '',
    '| Band | 5% / 25% / 50% / 75% / 95% | Below 6.7e3 | 6.7e3 to 1e5 | 1e5 to 1e6 |',
    '| --- | --- | --- | --- | --- |',
    ...rows.map(
      (r) =>
        `| M ${MACH_BANDS[r.band]![0]}-${MACH_BANDS[r.band]![1]} | ${quantiles(r.reD)} | ${share(r.reD, (x) => x < 6.7e3)} | ${share(r.reD, (x) => x >= 6.7e3 && x < 1e5)} | ${share(r.reD, (x) => x >= 1e5 && x <= 1e6)} |`,
    ),
    '',
  );
  // Trailing-edge half-angle of fins at the base (deg): 0 for square or
  // rounded trailing edges, the bevel for bevelled ones, atan(t/c) for a
  // double wedge (ridge at mid-chord); TN 3819 fig. 33's circular arcs of 5%
  // and 10% have 5.7 and 11.4 deg.
  const atBase = rockets.filter((r) => r.trailingEdgeAheadChords === 0);
  const half = atBase.map((r) =>
    r.section === 'bevel-both'
      ? r.bevelDeg
      : r.section === 'double-wedge'
        ? (Math.atan(r.thickness / r.rootChord) * 180) / Math.PI
        : 0,
  );
  lines.push(
    '## Fins at the base: trailing-edge half-angle, deg',
    '',
    `- fins at the base: ${atBase.length} of ${rockets.length}; square or rounded trailing edges (0 deg): ${share(half, (h) => h === 0)}; 0 to 5.7 deg: ${share(half, (h) => h > 0 && h <= 5.73)}; 5.7 to 11.4: ${share(half, (h) => h > 5.73 && h <= 11.42)}; above 11.4: ${share(half, (h) => h > 11.42)}`,
    `- t/c of fins at the base (5% / 25% / 50% / 75% / 95%): ${quantiles(atBase.map((r) => r.thickness / r.rootChord))}`,
    `- leading-edge sweep of fins at the base, deg: ${quantiles(atBase.map((r) => r.leadingEdgeSweepDeg))}`,
    '',
  );
  mkdirSync(join(here, 'out'), { recursive: true });
  writeFileSync(join(here, 'out', 'edges.out'), lines.join('\n'));
});
