/**
 * Stage A's revised scope (docs/design/0021-3d-euler-fins.md, the 2026-10-23
 * revision, section 5.3), estimated on the refusal audit's population
 * (./population.ts, the same seed and conditions as ./impact.test.ts). A
 * design-time estimate: no 3D solve exists, so the tests only a solve can
 * make (the grid gates, the fins' disturbance reaching the frozen bow shock,
 * families without a band, the device's memory) are not modelled, and every
 * share below is an upper bound on what Stage A could serve.
 *
 * Writes ./out/stage-a-scope.out. Run:
 *   ONLY=./stage-a-scope.test.ts nice -n 10 npx vitest run --config docs/research/refusals/vitest.config.ts
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'vitest';
import { FinRefusal } from '../../../src/fins/refusal';
import { exactSectionDrag } from '../../../src/fins/section-drag';
import { MACH_BANDS, drawAltitude, mulberry32, population, type Rocket } from './population';
import { librarySection, noseReasons, totalReasons, type ReasonKey } from './evaluate';

const here = dirname(fileURLToPath(import.meta.url));
const DEG = Math.PI / 180;

/** The lowest normal Mach number at which Stage A would serve a blunt leading edge (0021 revised, 2.6). */
const BLUNT_FLOORS = [1.3, 1.5] as const;

type Why =
  | 'nose not served (no 2D fitted field to start from)'
  | 'Mach below 1.2'
  | 'boat-tail (fins not wholly on the cylinder)'
  | 'sharp section: leading-edge shock detached'
  | 'sharp section: reflected wave (served only once rung b3 passes)'
  | 'blunt leading edge: normal Mach number below the floor';

interface Case {
  readonly r: Rocket;
  readonly band: number;
  readonly mach: number;
  readonly nose: readonly ReasonKey[];
  readonly total: readonly ReasonKey[];
}

/** Stage A's own refusals of a case (empty: the fins' pressure drag would be solved), at one blunt floor. */
function stageA(c: Case, floor: number, b3Passed: boolean): Why[] {
  const out: Why[] = [];
  if (c.mach < 1.2) out.push('Mach below 1.2');
  else if (c.nose.length > 0) out.push('nose not served (no 2D fitted field to start from)');
  if (c.r.boatTail) out.push('boat-tail (fins not wholly on the cylinder)');
  const s = c.r.section;
  if (s === 'double-wedge' || s === 'bevel-both' || s === 'bevel-le-square-te') {
    try {
      exactSectionDrag(librarySection(c.r) as never, c.mach);
    } catch (e) {
      if (!(e instanceof FinRefusal)) throw e;
      if (e.reason === 'reflected-wave') {
        if (!b3Passed) out.push('sharp section: reflected wave (served only once rung b3 passes)');
      } else out.push('sharp section: leading-edge shock detached');
    }
  } else {
    // Rounded or square leading edge on a flat plate: the leading-edge block, at the normal Mach number.
    const mn = c.mach * Math.cos(c.r.leadingEdgeSweepDeg * DEG);
    if (mn < floor) out.push('blunt leading edge: normal Mach number below the floor');
  }
  return out;
}

/** The reasons Stage A, where it serves, removes from a case's total (0021 revised, 5.3). */
function liftedBy(c: Case, squareInTotals: boolean): Set<ReasonKey> {
  const out = new Set<ReasonKey>(['sectionReflected']);
  if (squareInTotals) out.add('squareLe');
  return out;
}

const pct = (n: number, d: number) => `${((100 * n) / d).toFixed(1)}%`;

test('Stage A revised scope on the refusal population', () => {
  const rockets = population(2000);
  const rand = mulberry32(7);
  const cases: Case[] = [];
  for (const r of rockets) {
    MACH_BANDS.forEach(([lo, hi], band) => {
      const mach = lo + (hi - lo) * (0.0005 + 0.999 * rand());
      const altitudeKm = drawAltitude(rand(), rand());
      cases.push({ r, band, mach, nose: noseReasons(r, mach), total: totalReasons(r, { mach, altitudeKm }) });
    });
  }
  const bandName = (b: number) => (b < 0 ? 'all bands' : `M ${MACH_BANDS[b]![0].toFixed(1)}-${MACH_BANDS[b]![1].toFixed(1)}`);
  const sel = (b: number) => cases.filter((c) => b < 0 || c.band === b);
  const bands = [-1, 0, 1, 2, 3];
  const lines: string[] = [
    '# Stage A (0021, revised 2026-10-23): scope on the refusal population (generated by stage-a-scope.test.ts; do not edit)',
    '',
    'Upper bounds: grid gates, the frozen-shock check, families without a band and device memory are not modelled.',
    'Cases: 2000 rockets x one condition in each Mach band (the same draw as impact.test.ts, seed 7).',
    '',
  ];

  for (const floor of BLUNT_FLOORS) {
    lines.push(`## Blunt leading edges served from normal Mach ${floor}`, '');
    lines.push('| Share of cases | ' + bands.map(bandName).join(' | ') + ' |', '| --- |' + bands.map(() => ' --- |').join(''));
    const row = (name: string, f: (c: Case) => boolean) =>
      lines.push(`| ${name} | ` + bands.map((b) => pct(sel(b).filter(f).length, sel(b).length)).join(' | ') + ' |');
    row('fins solved (b3 not passed)', (c) => stageA(c, floor, false).length === 0);
    row('fins solved (b3 passed)', (c) => stageA(c, floor, true).length === 0);
    for (const s of ['rounded-le-square-te', 'rounded-both', 'square-both', 'bevel-both', 'bevel-le-square-te', 'double-wedge'] as const) {
      row(`  of which ${s} (b3 passed)`, (c) => c.r.section === s && stageA(c, floor, true).length === 0);
    }
    row('totals today', (c) => c.nose.length === 0 && c.total.length === 0);
    const withStageA = (square: boolean) => (c: Case) => {
      if (c.nose.length > 0) return false;
      if (stageA(c, floor, true).length > 0) return c.total.length === 0;
      const lifted = liftedBy(c, square);
      return c.total.every((k) => lifted.has(k));
    };
    row('totals with Stage A (b3 passed), square edges kept out of totals', withStageA(false));
    row('totals with Stage A (b3 passed), square edges in totals', withStageA(true));
    lines.push('');
    lines.push('Why Stage A refuses (a case may have several), all bands:', '');
    const whys = new Map<Why, number>();
    for (const c of cases) for (const w of stageA(c, floor, false)) whys.set(w, (whys.get(w) ?? 0) + 1);
    for (const [w, n] of [...whys].sort((a, b) => b[1] - a[1])) lines.push(`- ${w}: ${pct(n, cases.length)}`);
    lines.push('');
  }
  mkdirSync(join(here, 'out'), { recursive: true });
  writeFileSync(join(here, 'out', 'stage-a-scope.out'), lines.join('\n') + '\n');
});
