"""The size to expect of W9(a)'s effect, written with its registration (0009 section 9.4, 2026-10-30),
before any run of the method it registers.

At each (half-angle, Mach) node of W9(a)'s grid where the leading-edge shock is attached with supersonic
flow behind it, from the functions of flat_state.py (A2's review script, loaded here unchanged):

- the Mach number behind the straight shock (M1) and ln K = ln(p / rho^gamma) there, the free stream's 0;
- R, the reflection coefficient at the straight shock, (s - k) / (s + k) in flat_state.py's notation, the
  R of 0009 section 9.3's T3;
- the change of ln K across the shock as it weakens by 3 deg of turning (what a reflected C- line leaving
  the shock there crosses), with the change of nu that the entropy term turns it into behind the straight
  shock and the matching change of pressure;
- the plateau estimate of eps: the flat's fully developed change (flat_state.py's first reflections
  integrated over the whole front fan) carried whole onto the rear bevel, the bevel expanding from the
  changed flat state by the half-angle; eps = (p3 - p3') / (p1 - p3), p1 the front bevel's pressure, p3
  and p3' the rear bevel's without and with the change. An estimate of scale, not a bound.

Run from the repository root: python3 -I docs/research/refusals/scripts/w9_plateau.py > docs/research/refusals/out/w9-plateau.out
"""

import contextlib
import importlib.util
import io
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('flat_state', os.path.join(HERE, 'flat_state.py'))
fs = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(fs)
G = fs.G

THETA = list(range(5, 16))
MACH = [1.5, 1.6, 1.7, 1.8, 1.9, 2.0, 2.2, 2.4, 2.6, 2.8, 3.0]


def ln_k(minf, th):
    b, p, _ = fs.shock(minf, th)
    mn1 = minf * math.sin(b)
    rho = (G + 1) * mn1 ** 2 / ((G - 1) * mn1 ** 2 + 2)
    return math.log(p / rho ** G)


def expand(m, p, turn):
    mo = fs.pm_inv(fs.pm(m) + turn)
    return mo, p * fs.iso(mo) / fs.iso(m)


rows = []
print('# W9(a): the size to expect, by node (generated by scripts/w9_plateau.py; do not edit)')
print()
print('| Half-angle, deg | Mach | M1 | ln K behind the shock | R at the straight shock | change of ln K over 3 deg of weakening | its change of nu, deg | its change of p, % | plateau eps, % |')
print('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
for t in THETA:
    for minf in MACH:
        th = math.radians(t)
        r = fs.shock(minf, th)
        if r is None or r[2] <= 1:
            continue
        _, p1, m1 = r
        k = fs.K(m1)
        s = fs.S(minf, th)
        big_r = (s - k) / (s + k)
        lk = ln_k(minf, th)
        dlk = lk - ln_k(minf, th - math.radians(3))
        c = math.sqrt(m1 * m1 - 1) / (G * (G - 1) * m1 * m1)
        dnu = c * dlk
        dp = G * m1 * m1 / math.sqrt(m1 * m1 - 1) * dnu
        run = fs.run(minf, t)
        _, p3 = expand(run['M2'], run['p2'], th)
        _, p3r = expand(run['M2r'], run['p2r'], th)
        eps = (p3 - p3r) / (p1 - p3)
        rows.append((t, minf, m1, lk, big_r, eps))
        print('| %d | %.1f | %.3f | %.5f | %+.4f | %.5f | %.3f | %.2f | %+.3f |'
              % (t, minf, m1, lk, big_r, dlk, math.degrees(dnu), 100 * dp, 100 * eps))
print()


def summary(name, sel):
    e = sorted(abs(r[5]) for r in sel)
    n = len(e)
    big = max(sel, key=lambda r: abs(r[5]))
    print('- %s (%d nodes): |eps| at most %.3f%% (%d deg, Mach %.1f), median %.3f%%, tenth to ninetieth percentile %.3f%% to %.3f%%'
          % (name, n, 100 * big[5], big[0], big[1], 100 * e[n // 2], 100 * e[n // 10], 100 * e[(9 * n) // 10]))


print('- ln K behind the straight shock: %.5f to %.5f' % (min(r[3] for r in rows), max(r[3] for r in rows)))
summary('every attached node', rows)
summary('nodes with M1 of 1.1 or more', [r for r in rows if r[2] >= 1.1])
