/**
 * What the reflected-wave refusal still holds after 0009 section 8 (A2 of the refusal plan, 2026-10-26),
 * on impact.test.ts's own cases: per section and Mach band, the cases the old rule refused (a reflected wave
 * landing anywhere ahead of the trailing edge), the cases the present rule refuses (one landing ahead of the
 * end of the last face with slope), and, for the hexagons still refused, whether the first landing is on the
 * flat ahead of the rear bevel or on the rear bevel itself. The present count is checked against
 * evaluate.ts's own `sectionReflected` on every case: a check of the bookkeeping, not of 0009 section 8,
 * since both call the same exactSectionDrag. Writes out/reflected-split.out (or into OUT_DIR).
 *
 *   ONLY=./reflected-split.test.ts nice -n 10 npx vitest run --config docs/research/refusals/vitest.config.ts
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, test } from 'vitest';
import { exactSectionDrag } from '../../../src/fins/section-drag';
import type { SymmetricSection } from '../../../src/fins/section';
import { librarySection, totalReasons } from './evaluate';
import { MACH_BANDS, drawAltitude, mulberry32, population } from './population';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = process.env.OUT_DIR === undefined ? join(here, 'out') : process.env.OUT_DIR;
const N_ROCKETS = Number(process.env.N_ROCKETS ?? 2000);

test('the reflected-wave refusal, split', () => {
  const rockets = population(N_ROCKETS);
  // impact.test.ts's draws: per rocket, per band, the Mach number and then the altitude (seed 7).
  const rand = mulberry32(7);
  const rows = new Map<string, number[]>();
  const add = (row: string, band: number) => {
    const r = rows.get(row) ?? MACH_BANDS.map(() => 0);
    r[band]!++;
    rows.set(row, r);
  };
  let agree = 0;
  let checked = 0;
  for (const rocket of rockets) {
    MACH_BANDS.forEach(([lo, hi], band) => {
      const mach = lo + (hi - lo) * (0.0005 + 0.999 * rand());
      const altitudeKm = drawAltitude(rand(), rand());
      const s = rocket.section;
      if (s !== 'bevel-both' && s !== 'bevel-le-square-te' && s !== 'double-wedge') return;
      const section = librarySection(rocket) as SymmetricSection;
      let refusedNow = false;
      try {
        const v = exactSectionDrag(section, mach, { neglectReflectedWaves: true });
        const x1 = Math.min(v.upper.firstReflection, v.lower.firstReflection);
        if (x1 < 1) add(`${s}: refused before 0009 section 8 (a landing ahead of the trailing edge)`, band);
        if (!v.exact) {
          refusedNow = true;
          add(`${s}: refused now (a landing ahead of the end of the last face with slope)`, band);
          if (s === 'bevel-both') {
            const rearStart = section.x[section.x.length - 2]!;
            add(
              x1 < rearStart
                ? 'bevel-both refused now: first landing on the flat, ahead of the rear bevel'
                : 'bevel-both refused now: first landing on the rear bevel',
              band,
            );
          }
        }
      } catch {
        // Detached or subsonic behind the shock: another reason (sectionDetached), not counted here.
      }
      checked++;
      if (refusedNow === totalReasons(rocket, { mach, altitudeKm }).includes('sectionReflected')) agree++;
    });
  }
  expect(agree).toBe(checked);
  const lines = [
    '# The reflected-wave refusal, split (generated by reflected-split.test.ts; do not edit)',
    '',
    `- rockets: ${N_ROCKETS}, each at one condition per Mach band (impact.test.ts's cases)`,
    `- sharp sections checked: ${checked}; present verdict agreeing with evaluate.ts's sectionReflected: ${agree}`,
    '',
    `| Cases | ${MACH_BANDS.map(([lo, hi]) => `M ${lo.toFixed(1)}-${hi.toFixed(1)}`).join(' | ')} | All |`,
    `| --- | ${MACH_BANDS.map(() => '---').join(' | ')} | --- |`,
    ...[...rows.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([row, n]) => `| ${row} | ${n.join(' | ')} | ${n.reduce((a, b) => a + b, 0)} |`),
    '',
  ];
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'reflected-split.out'), lines.join('\n'));
});
