/**
 * The advice replay (the review of 55a76d2, its blocking finding): for every case of the baseline
 * population (impact.test.ts's 2000 rockets, at one Mach number in each band, seed 7) whose body
 * base is refused for its fins, as evaluate.ts asks it (a cylindrical afterbody, a turbulent layer),
 * how the chain of the words' changes ended (src/base/base-drag.ts, followAdvice): the last change
 * served, no mechanical change advised (the last reason named), a reason met again, or the steps
 * run out. A case whose advised end state is not served must be named here with its reason.
 * Writes ./out/advice-replay.out. Run:
 *
 *   ONLY=./advice-replay.test.ts nice -n 15 npx vitest run --config docs/research/refusals/vitest.config.ts
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, test } from 'vitest';
import { bodyBaseDrag } from '../../../src/base/base-drag';
import { BaseRefusal } from '../../../src/base/refusal';
import { rocketBaseFins } from './evaluate';
import { MACH_BANDS, drawAltitude, mulberry32, population } from './population';

const here = dirname(fileURLToPath(import.meta.url));
const N_ROCKETS = Number(process.env.N_ROCKETS ?? 2000);

test('every advised end state: served, or named', () => {
  const rockets = population(N_ROCKETS);
  const rand = mulberry32(7);
  let cases = 0;
  let asked = 0;
  let servedFirst = 0;
  const ends = new Map<string, number>();
  const noChange = new Map<string, number>();
  const short: string[] = [];
  const bySection = new Map<string, Map<string, number>>();
  const bump = (m: Map<string, number>, k: string) => m.set(k, (m.get(k) ?? 0) + 1);
  for (const [index, rocket] of rockets.entries()) {
    for (const [lo, hi] of MACH_BANDS) {
      const mach = lo + (hi - lo) * (0.0005 + 0.999 * rand());
      drawAltitude(rand(), rand());
      cases++;
      if (!(mach >= 1.0 && mach <= 3.0)) continue;
      asked++;
      try {
        bodyBaseDrag({
          mach,
          afterbody: 'cylinder',
          boundaryLayerAtBase: 'turbulent',
          baseAreaRatio: 1,
          fins: rocketBaseFins(rocket),
        });
        servedFirst++;
      } catch (e) {
        if (!(e instanceof BaseRefusal)) throw e;
        const end = e.endedBy ?? 'none';
        bump(ends, end);
        const sec = bySection.get(rocket.section) ?? new Map<string, number>();
        bySection.set(rocket.section, sec);
        bump(sec, end);
        const last = e.further?.at(-1)?.reason ?? e.reason;
        if (end === 'no-change') bump(noChange, last);
        if (end === 'repeat' || end === 'steps') {
          short.push(
            `rocket ${index} (${rocket.section}, ${rocket.finCount} fins), M ${mach.toFixed(3)}: ` +
              [e.reason, ...(e.further ?? []).map((f) => `${f.after}: ${f.reason}`)].join(' -> ') +
              ` (${end})`,
          );
        }
      }
    }
  }
  const lines = [
    '# Advice replay (generated by advice-replay.test.ts; do not edit)',
    '',
    `- cases: ${cases} (${N_ROCKETS} rockets at four Mach bands); the body base asked at Mach 1.0 to 3.0: ${asked}`,
    `- served at once: ${servedFirst}; refused: ${asked - servedFirst}`,
    '',
    '## How each refusal\'s chain of advised changes ended',
    '',
    '| Ended | Cases |',
    '| --- | --- |',
    ...[...ends.entries()].sort().map(([k, v]) => `| ${k} | ${v} |`),
    '',
    '## By the rocket\'s section',
    '',
    '| Section | Ended | Cases |',
    '| --- | --- | --- |',
    ...[...bySection.entries()]
      .sort()
      .flatMap(([sec, m]) => [...m.entries()].sort().map(([k, v]) => `| ${sec} | ${k} | ${v} |`)),
    '',
    '## No mechanical change advised: the last reason met (named, not a change of the fins)',
    '',
    '| Last reason | Cases |',
    '| --- | --- |',
    ...[...noChange.entries()].sort().map(([k, v]) => `| ${k} | ${v} |`),
    '',
    '## Advice that fell short (a reason met again, or the steps run out)',
    '',
    ...(short.length === 0 ? ['none'] : short.map((s) => `- ${s}`)),
    '',
  ];
  mkdirSync(join(here, 'out'), { recursive: true });
  writeFileSync(join(here, 'out', 'advice-replay.out'), lines.join('\n'));
  expect(asked).toBeGreaterThan(0);
});
