"""Overlay the two readings of fig 18 curves on the page (red: this audit's
traced curve pixels; blue: first reading's curve values via its own
calibration M = 1 + (x-397)/298.4, P_B = -(1804.6-y)/3008)."""
import sys
from PIL import Image, ImageDraw
im = Image.open(sys.argv[1]).convert("RGB")
x0, y0, x1, y1, s = map(float, sys.argv[3:8])
d = ImageDraw.Draw(im)
mine = [(404, 1236.9), (404, 1251.1), (452, 1243.9), (452, 1254.2), (548, 1273.9), (548, 1286.9), (596, 1296.0), (596, 1311.5),
        (656, 1330.5), (656, 1347.4), (692, 1353.6), (692, 1368.6), (752, 1392.7), (752, 1403.5), (800, 1421.0), (800, 1429.4),
        (860, 1453.0), (860, 1459.9), (908, 1475.5), (908, 1480.9), (956, 1496.1), (956, 1500.0), (1092, 1546.0), (1188, 1575.5), (1188, 1582.7),
        (1272, 1597.9), (1272, 1608.0), (1404, 1630.5), (1404, 1639.5)]
first = [(1.52, -0.177), (1.52, -0.170), (1.63, -0.170), (1.63, -0.162), (1.94, -0.145), (1.94, -0.142), (2.42, -0.123), (2.42, -0.117),
         (2.68, -0.112), (2.68, -0.108), (3.26, -0.091), (3.26, -0.088), (3.51, -0.085), (3.51, -0.082), (1.5, -0.177), (1.5, -0.173),
         (2.0, -0.145), (2.0, -0.139), (2.5, -0.118), (2.5, -0.116), (3.0, -0.101), (3.0, -0.096)]
for x, y in mine:
    d.ellipse([x - 2, y - 2, x + 2, y + 2], outline=(255, 0, 0))
for M, P in first:
    x = 397 + (M - 1) * 298.4; y = 1804.6 + P * 3008
    d.line([x - 6, y, x + 6, y], fill=(0, 0, 255), width=1); d.line([x, y - 6, x, y + 6], fill=(0, 0, 255), width=1)
im = im.crop((int(x0), int(y0), int(x1), int(y1)))
im = im.resize((int((x1 - x0) * s), int((y1 - y0) * s)), Image.LANCZOS)
im.save(sys.argv[2])
